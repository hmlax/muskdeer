-- Upgrade only the exact historical stateless fork. Deleted historical audit
-- rows cannot be reconstructed; these tables record future operations only.
-- Retain every budget/projection row, legacy column and migration checksum.
DO $$
BEGIN
  IF to_regclass('himalaya_intents') IS NOT NULL OR to_regclass('himalaya_cancellations') IS NOT NULL
      OR to_regclass('himalaya_development_baselines') IS NOT NULL OR to_regclass('synthetic_tape_intents') IS NOT NULL THEN
    RAISE EXCEPTION 'stateless migration history differs from physical audit schema' USING ERRCODE = '55000';
  END IF;
END $$;
ALTER TABLE himalaya_budgets RENAME TO trading_account_policies;
ALTER TABLE himalaya_projections RENAME TO venue_account_snapshots;
CREATE TABLE venue_order_intents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    account_id varchar(64) NOT NULL REFERENCES trading_account_policies(account_id),
    user_id bigint NOT NULL CHECK (user_id > 0),
    fund_id bigint NOT NULL CHECK (fund_id > 0),
    symbol varchar(32) NOT NULL,
    client_id varchar(128) NOT NULL UNIQUE,
    owner_id varchar(128) NOT NULL,
    owner_epoch bigint NOT NULL CHECK (owner_epoch > 0),
    request_digest varchar(64) NOT NULL,
    side varchar(8) NOT NULL CHECK (side IN ('BUY', 'SELL')),
    price numeric(76,36) NOT NULL CHECK (price > 0),
    quantity numeric(76,36) NOT NULL CHECK (quantity > 0),
    leverage integer NOT NULL CHECK (leverage BETWEEN 1 AND 150),
    state varchar(16) NOT NULL CHECK (state IN ('PREPARED', 'DISPATCHED', 'ACKNOWLEDGED', 'TERMINAL')),
    order_id varchar(20) NOT NULL,
    reserved_notional numeric(76,36) NOT NULL CHECK (reserved_notional > 0)
);
CREATE INDEX idx_himalaya_intent_account ON venue_order_intents(account_id, state);

CREATE TABLE venue_cancellations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  create_at bigint NOT NULL,
  update_at bigint NOT NULL,
  delete_at bigint NULL,
  account_id varchar(64) NOT NULL REFERENCES execution_shard_leases(account_id),
  user_id bigint NOT NULL CHECK (user_id > 0),
  fund_id bigint NOT NULL CHECK (fund_id > 0),
  symbol varchar(32) NOT NULL,
  order_id varchar(20) NOT NULL,
  owner_id varchar(128) NOT NULL,
  owner_epoch bigint NOT NULL CHECK (owner_epoch > 0),
  request_digest varchar(64) NOT NULL,
  state varchar(16) NOT NULL CHECK (state IN ('PREPARED','DISPATCHED','CONFIRMED'))
);
CREATE INDEX idx_himalaya_cancel_account ON venue_cancellations(account_id, order_id, state);
CREATE TABLE synthetic_tape_intents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  create_at bigint NOT NULL,
  update_at bigint NOT NULL,
  delete_at bigint NULL,
  run_id varchar(20) NOT NULL,
  symbol varchar(32) NOT NULL,
  sequence bigint NOT NULL CHECK (sequence >= 0 AND sequence < 1000),
  policy_digest varchar(64) NOT NULL,
  plan jsonb NOT NULL,
  notional numeric(76,36) NOT NULL CHECK (notional > 0),
  result jsonb NOT NULL,
  CONSTRAINT uk_synthetic_tape_slot UNIQUE (run_id, symbol, sequence)
);
CREATE TABLE execution_recovery_baselines (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  create_at bigint NOT NULL,
  update_at bigint NOT NULL,
  delete_at bigint NULL,
  account_id varchar(64) NOT NULL UNIQUE REFERENCES execution_shard_leases(account_id),
  request jsonb NOT NULL,
  request_digest varchar(64) NOT NULL,
  evidence_digest varchar(64) NOT NULL,
  snapshot jsonb NOT NULL,
  legacy_notional numeric(76,36) NOT NULL CHECK (legacy_notional > 0),
  minimum_observed_notional numeric(76,36) NOT NULL CHECK (minimum_observed_notional >= legacy_notional)
);

CREATE TABLE runtime_policy_migrations (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 create_at bigint NOT NULL, update_at bigint NOT NULL, delete_at bigint NULL,
 version bigint NOT NULL CONSTRAINT uk_runtime_policy_migration_version UNIQUE,
 checksum varchar(64) NOT NULL
);
CREATE TABLE service_runtime_policies (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 create_at bigint NOT NULL, update_at bigint NOT NULL, delete_at bigint NULL,
 service_name varchar(32) NOT NULL CONSTRAINT uk_service_runtime_policy_service UNIQUE
   CHECK (service_name IN ('market','strategy','execution','portfolio')),
 revision bigint NOT NULL CHECK (revision > 0),
 parameters_schema_version bigint NOT NULL CHECK (parameters_schema_version = 1),
 parameters jsonb NOT NULL CHECK (jsonb_typeof(parameters) = 'object'),
 parameters_digest varchar(64) NOT NULL CHECK (parameters_digest ~ '^[0-9a-f]{64}$')
);

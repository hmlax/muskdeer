-- Add only the long-grid cursor/journal. Existing trading/audit rows are retained.
CREATE TABLE long_grid_runtimes (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 create_at bigint NOT NULL,
 update_at bigint NOT NULL,
 delete_at bigint,
 instance_id bigint NOT NULL UNIQUE REFERENCES strategy_instances(id),
 revision bigint NOT NULL CHECK(revision > 0),
 state varchar(16) NOT NULL CHECK(state IN ('RUNNING','STOPPING','STOPPED')),
 started boolean NOT NULL,
 next_buy_price numeric(76,36) NOT NULL CHECK(next_buy_price >= 0),
 lots jsonb NOT NULL CHECK(jsonb_typeof(lots)='object'),
 pending_action_id bigint,
 stop_action_id bigint,
 next_sequence bigint NOT NULL CHECK(next_sequence >= 0),
 halted_control_version bigint NOT NULL CHECK(halted_control_version >= 0)
);
CREATE TABLE long_grid_actions (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 create_at bigint NOT NULL,
 update_at bigint NOT NULL,
 delete_at bigint,
 instance_id bigint NOT NULL REFERENCES strategy_instances(id),
 revision bigint NOT NULL CHECK(revision > 0),
 sequence bigint NOT NULL CHECK(sequence >= 0),
 client_id varchar(128) NOT NULL UNIQUE,
 kind varchar(16) NOT NULL CHECK(kind IN ('INITIAL_BUY','GRID_BUY','TAKE_PROFIT','STOP_LOSS')),
 side varchar(8) NOT NULL CHECK(side IN ('BUY','SELL')),
 price numeric(76,36) NOT NULL CHECK(price >= 0),
 quantity numeric(76,36) NOT NULL CHECK(quantity > 0),
 position_id varchar(128) NOT NULL,
 lot_sequence bigint NOT NULL CHECK(lot_sequence >= 0),
 state varchar(16) NOT NULL CHECK(state IN ('PREPARED','DISPATCHED','ACK','UNKNOWN','REJECTED','TERMINAL')),
 order_id varchar(20) NOT NULL,
 executed_quantity numeric(76,36) NOT NULL CHECK(executed_quantity >= 0 AND executed_quantity <= quantity),
 executed_notional numeric(76,36) NOT NULL CHECK(executed_notional >= 0),
 UNIQUE(instance_id,sequence),
 CHECK((side='BUY' AND kind IN ('INITIAL_BUY','GRID_BUY')) OR (side='SELL' AND kind IN ('TAKE_PROFIT','STOP_LOSS') AND position_id<>'')),
 CHECK((kind='STOP_LOSS' AND price=0) OR (kind<>'STOP_LOSS' AND price>0))
);
ALTER TABLE long_grid_runtimes ADD CONSTRAINT long_grid_pending_action FOREIGN KEY(pending_action_id) REFERENCES long_grid_actions(id);
ALTER TABLE long_grid_runtimes ADD CONSTRAINT long_grid_stop_action FOREIGN KEY(stop_action_id) REFERENCES long_grid_actions(id);
CREATE INDEX long_grid_actions_instance_recent ON long_grid_actions(instance_id,id DESC);

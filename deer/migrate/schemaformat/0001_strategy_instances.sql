CREATE FUNCTION guard_template_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.strategy_type IS DISTINCT FROM OLD.strategy_type OR NEW.template_key IS DISTINCT FROM OLD.template_key THEN
  RAISE EXCEPTION 'template algorithm identity is immutable';
 END IF;
 IF (NEW.implementation IS DISTINCT FROM OLD.implementation OR NEW.required_inputs IS DISTINCT FROM OLD.required_inputs OR NEW.parameter_contract IS DISTINCT FROM OLD.parameter_contract OR NEW.enabled IS DISTINCT FROM OLD.enabled) AND NEW.revision <> OLD.revision + 1 THEN
  RAISE EXCEPTION 'template edit requires next revision and explicit instance rebinding';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER template_revision BEFORE UPDATE ON strategy_templates FOR EACH ROW EXECUTE FUNCTION guard_template_revision();

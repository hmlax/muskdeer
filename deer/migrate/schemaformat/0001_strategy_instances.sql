-- A configuration edit must advance the revision consumed by final SDK fencing.
-- Runtime state reporting does not change configuration identity.
CREATE FUNCTION guard_instance_revision() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF NEW.account_id IS DISTINCT FROM OLD.account_id OR NEW.instrument_id IS DISTINCT FROM OLD.instrument_id OR NEW.template IS DISTINCT FROM OLD.template THEN
  RAISE EXCEPTION 'instance financial and algorithm identity is immutable';
 END IF;
 IF (NEW.template_id IS DISTINCT FROM OLD.template_id OR NEW.template_revision IS DISTINCT FROM OLD.template_revision OR NEW.parameters IS DISTINCT FROM OLD.parameters OR NEW.implementation IS DISTINCT FROM OLD.implementation OR NEW.market_data_source IS DISTINCT FROM OLD.market_data_source OR NEW.desired_running IS DISTINCT FROM OLD.desired_running OR NEW.tape_policy_digest IS DISTINCT FROM OLD.tape_policy_digest OR NEW.tape_parameters_digest IS DISTINCT FROM OLD.tape_parameters_digest) AND NEW.revision <> OLD.revision + 1 THEN
  RAISE EXCEPTION 'configuration edit requires next instance revision';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER instance_revision BEFORE UPDATE ON strategy_instances FOR EACH ROW EXECUTE FUNCTION guard_instance_revision();


CREATE TABLE admin_strategy_publications (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL CHECK (delete_at IS NULL),
    actor_user_id bigint NOT NULL REFERENCES admin_users(id),
    actor_session_id bigint NOT NULL REFERENCES admin_sessions(id),
    strategy_instance_id bigint NOT NULL REFERENCES strategy_instances(id),
    audit_id bigint NOT NULL CONSTRAINT uk_admin_strategy_publication_audit UNIQUE REFERENCES admin_audits(id),
    idempotency_key varchar(64) NOT NULL CHECK (idempotency_key ~ '^[A-Za-z0-9_.:-]{16,64}$'),
    request_fingerprint char(64) NOT NULL CHECK (request_fingerprint ~ '^[0-9a-f]{64}$'),
    previous_config_version bigint NOT NULL CHECK (previous_config_version > 0),
    config_version bigint NOT NULL CHECK (config_version > previous_config_version),
    previous_revision bigint NOT NULL CHECK (previous_revision > 0),
    revision bigint NOT NULL CHECK (revision > previous_revision AND revision - previous_revision = 1),
    market_data_source varchar(32) NOT NULL CHECK (market_data_source IN ('binance', 'okx')),
    reason varchar(256) NOT NULL CHECK (length(reason) > 0),
    CONSTRAINT uk_admin_strategy_publication_key UNIQUE (actor_user_id, idempotency_key),
    CONSTRAINT uk_admin_strategy_publication_version UNIQUE (strategy_instance_id, config_version),
    CONSTRAINT fk_admin_publication_config FOREIGN KEY (strategy_instance_id, config_version, market_data_source)
        REFERENCES strategy_config_versions(instance_id, version, market_data_source)
);

CREATE FUNCTION guard_admin_strategy_publication() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    principal admin_users%ROWTYPE;
    session admin_sessions%ROWTYPE;
    audit admin_audits%ROWTYPE;
    strategy strategy_instances%ROWTYPE;
    config strategy_config_versions%ROWTYPE;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_publication_history', MESSAGE = 'publication history is immutable';
    END IF;
    SELECT * INTO principal FROM admin_users WHERE id = NEW.actor_user_id FOR SHARE;
    SELECT * INTO session FROM admin_sessions WHERE id = NEW.actor_session_id FOR SHARE;
    SELECT * INTO strategy FROM strategy_instances WHERE id = NEW.strategy_instance_id FOR SHARE;
    IF principal.id IS NULL OR session.id IS NULL OR NOT principal.enabled OR principal.delete_at IS NOT NULL OR
       principal.role NOT IN ('operator', 'admin') OR session.user_id <> principal.id OR session.delete_at IS NOT NULL OR
       session.revoked_at IS NOT NULL OR session.credential_version <> principal.credential_version OR
       session.expires_at <= floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_publication_authority', MESSAGE = 'publication requires current operator authority';
    END IF;
    SELECT * INTO audit FROM admin_audits WHERE id = NEW.audit_id;
    SELECT * INTO config FROM strategy_config_versions WHERE instance_id = NEW.strategy_instance_id AND version = NEW.config_version;
    IF audit.id IS NULL OR audit.delete_at IS NOT NULL OR audit.actor <> principal.username OR audit.actor_role <> principal.role OR
       audit.action <> 'strategy.publish' OR audit.resource <> 'strategy_instance:' || NEW.strategy_instance_id::text OR
       audit.reason <> NEW.reason OR audit.before_version IS DISTINCT FROM NEW.previous_revision OR audit.after_version IS DISTINCT FROM NEW.revision THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_publication_audit', MESSAGE = 'publication requires matching immutable audit';
    END IF;
    IF strategy.id IS NULL OR strategy.delete_at IS NOT NULL OR strategy.revision <> NEW.revision OR
       strategy.requested_config_version <> NEW.config_version OR strategy.market_data_source <> NEW.market_data_source OR
       config.id IS NULL OR config.delete_at IS NOT NULL OR config.parameters_schema_version <> 1 OR
       config.template <> strategy.template OR config.code_version <> strategy.code_version OR
       config.market_data_source <> NEW.market_data_source OR config.created_by <> principal.username OR
       NOT EXISTS (SELECT 1 FROM strategy_config_versions WHERE instance_id = strategy.id AND version = NEW.previous_config_version) OR
       EXISTS (SELECT 1 FROM risk_snapshots WHERE strategy_instance_id = strategy.id AND delete_at IS NULL AND allow_new_risk) OR
       EXISTS (SELECT 1 FROM admin_strategy_operations WHERE strategy_instance_id = strategy.id AND state = 'ACCEPTED'
           AND (config_version <> NEW.config_version OR market_data_source <> NEW.market_data_source OR target_state <> strategy.desired_state)) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_publication_effect', MESSAGE = 'publication requires requested input and closed old risk';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER admin_strategy_publication BEFORE INSERT OR UPDATE OR DELETE ON admin_strategy_publications
    FOR EACH ROW EXECUTE FUNCTION guard_admin_strategy_publication();

ALTER TABLE risk_snapshots DROP CONSTRAINT risk_snapshots_reason_code_check;
ALTER TABLE risk_snapshots ADD CONSTRAINT risk_snapshots_reason_code_check CHECK (
    reason_code IN ('NOT_EVALUATED', 'READY', 'STRATEGY_STOPPED', 'INVALID_PARAMETERS', 'BUDGET_DISABLED',
        'UNRECONCILED', 'MARKET_UNAVAILABLE', 'CONFIGURATION_PENDING')
);

-- A periodic evaluator or an older writer must not reopen old-version orders
-- during quiescence. Existing fills/observations and old-version CANCEL remain
-- available. The core holds the strategy mutex before any financial effect.
CREATE FUNCTION validate_simulator_requested_configuration() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    strategy strategy_instances%ROWTYPE;
BEGIN
    IF NEW.action = 'CANCEL' THEN
        RETURN NULL;
    END IF;
    SELECT * INTO strategy FROM strategy_instances WHERE id = NEW.strategy_instance_id FOR SHARE;
    IF strategy.active_config_version IS DISTINCT FROM strategy.requested_config_version
        OR strategy.active_market_data_source IS DISTINCT FROM strategy.market_data_source THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001', CONSTRAINT = 'simulator_configuration_pending', MESSAGE = 'requested configuration is not active';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER simulator_requested_configuration AFTER INSERT ON simulator_commands
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_simulator_requested_configuration();

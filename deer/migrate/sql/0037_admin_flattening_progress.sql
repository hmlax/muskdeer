-- Work stages are retained separately from immutable confirmations. Neither
-- QUEUED nor ACTIVE grants order admission, dispatch or completion.
CREATE TABLE admin_account_flattening_tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL CHECK (create_at > 0),
    update_at bigint NOT NULL CHECK (update_at >= create_at),
    delete_at bigint NULL CHECK (delete_at IS NULL),
    flattening_id bigint NOT NULL CONSTRAINT uk_admin_flatten_task_confirmation UNIQUE REFERENCES admin_account_flattenings(id),
    strategy_instance_id bigint NOT NULL REFERENCES strategy_instances(id),
    account_id varchar(64) NOT NULL REFERENCES simulator_accounts(account_id),
    instrument_id bigint NOT NULL REFERENCES instruments(id),
    state varchar(16) NOT NULL CHECK (state IN ('QUEUED', 'ACTIVE')),
    revision bigint NOT NULL CHECK (revision > 0),
    owner_id varchar(128) NULL,
    owner_epoch bigint NULL,
    claimed_at bigint NULL,
    CONSTRAINT ck_admin_flatten_task_claim CHECK (
        (state = 'QUEUED' AND revision = 1 AND owner_id IS NULL AND owner_epoch IS NULL AND claimed_at IS NULL)
        OR (state = 'ACTIVE' AND revision > 1 AND owner_id IS NOT NULL AND owner_id ~ '^[A-Za-z0-9_.-]{1,64}\.[0-9a-f]{32}$'
            AND owner_epoch IS NOT NULL AND owner_epoch > 0 AND claimed_at IS NOT NULL AND claimed_at >= create_at AND claimed_at <= update_at)
    )
);
CREATE INDEX idx_admin_flatten_task_strategy ON admin_account_flattening_tasks(strategy_instance_id, id);
CREATE UNIQUE INDEX uk_admin_flatten_task_active_account ON admin_account_flattening_tasks(account_id) WHERE state = 'ACTIVE';

CREATE FUNCTION guard_admin_flatten_task_history() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE confirmation admin_account_flattenings%ROWTYPE;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_flatten_task_history', MESSAGE = 'flatten work cannot be deleted';
    END IF;
    IF TG_OP = 'UPDATE' THEN
        IF NEW.revision <> OLD.revision + 1 OR NEW.state <> 'ACTIVE' OR
           ROW(NEW.id, NEW.create_at, NEW.flattening_id, NEW.strategy_instance_id, NEW.account_id, NEW.instrument_id, NEW.delete_at)
           IS DISTINCT FROM ROW(OLD.id, OLD.create_at, OLD.flattening_id, OLD.strategy_instance_id, OLD.account_id, OLD.instrument_id, OLD.delete_at) OR
           (OLD.state = 'ACTIVE' AND (NEW.owner_epoch <= OLD.owner_epoch OR NEW.claimed_at < OLD.claimed_at)) THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_flatten_task_history', MESSAGE = 'flatten work identity and ownership revision cannot be rewritten';
        END IF;
    ELSE
        IF NEW.state <> 'QUEUED' OR NEW.revision <> 1 OR NEW.owner_id IS NOT NULL OR NEW.owner_epoch IS NOT NULL OR NEW.claimed_at IS NOT NULL OR NEW.delete_at IS NOT NULL THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_flatten_task_initial', MESSAGE = 'flatten work must begin queued and unclaimed';
        END IF;
    END IF;
    SELECT * INTO confirmation FROM admin_account_flattenings WHERE id = NEW.flattening_id;
    IF confirmation.id IS NULL OR ROW(NEW.strategy_instance_id, NEW.account_id, NEW.instrument_id)
       IS DISTINCT FROM ROW(confirmation.strategy_instance_id, confirmation.account_id, confirmation.instrument_id) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_flatten_task_scope', MESSAGE = 'flatten work must retain its confirmed scope';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER admin_flatten_task_history BEFORE INSERT OR UPDATE OR DELETE ON admin_account_flattening_tasks
    FOR EACH ROW EXECUTE FUNCTION guard_admin_flatten_task_history();

CREATE FUNCTION guard_admin_flatten_task_owner() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    task admin_account_flattening_tasks%ROWTYPE;
    lease strategy_leases%ROWTYPE;
    strategy strategy_instances%ROWTYPE;
    now_ms bigint;
BEGIN
    SELECT * INTO task FROM admin_account_flattening_tasks WHERE id = NEW.id;
    IF task.state = 'ACTIVE' THEN
        -- Match the existing admission/lifecycle order: waiting for a strategy
        -- must not hold a lease that its current final sender still needs.
        SELECT * INTO strategy FROM strategy_instances WHERE id = task.strategy_instance_id FOR SHARE;
        SELECT * INTO lease FROM strategy_leases WHERE strategy_instance_id = task.strategy_instance_id FOR SHARE;
        now_ms := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
        IF lease.id IS NULL OR lease.delete_at IS NOT NULL OR lease.owner_id IS DISTINCT FROM task.owner_id OR lease.epoch IS DISTINCT FROM task.owner_epoch OR lease.expires_at <= now_ms OR
           strategy.id IS NULL OR strategy.delete_at IS NOT NULL OR strategy.runtime_owner_id IS DISTINCT FROM task.owner_id OR strategy.runtime_owner_epoch IS DISTINCT FROM task.owner_epoch OR
           strategy.account_id <> task.account_id OR strategy.instrument_id <> task.instrument_id THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_flatten_task_owner', MESSAGE = 'flatten work claim requires current strategy ownership';
        END IF;
        IF task.claimed_at > now_ms THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_flatten_task_clock', MESSAGE = 'flatten work claim cannot use a future observation';
        END IF;
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER admin_flatten_task_owner_commit AFTER INSERT OR UPDATE ON admin_account_flattening_tasks
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION guard_admin_flatten_task_owner();

-- Existing confirmations get only pending markers. No order, ownership, final
-- quantity observation, risk permission or success is fabricated by upgrade.
INSERT INTO admin_account_flattening_tasks(create_at, update_at, flattening_id, strategy_instance_id, account_id, instrument_id, state, revision)
    SELECT floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint, floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint,
        id, strategy_instance_id, account_id, instrument_id, 'QUEUED', 1 FROM admin_account_flattenings;

CREATE FUNCTION initialize_admin_flatten_task() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE now_ms bigint;
BEGIN
    now_ms := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
    INSERT INTO admin_account_flattening_tasks(create_at, update_at, flattening_id, strategy_instance_id, account_id, instrument_id, state, revision)
        VALUES (now_ms, now_ms, NEW.id, NEW.strategy_instance_id, NEW.account_id, NEW.instrument_id, 'QUEUED', 1);
    RETURN NULL;
END;
$$;
CREATE TRIGGER admin_flatten_task_initialize AFTER INSERT ON admin_account_flattenings
    FOR EACH ROW EXECUTE FUNCTION initialize_admin_flatten_task();


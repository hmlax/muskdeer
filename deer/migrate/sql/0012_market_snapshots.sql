ALTER TABLE market_feeds ADD CONSTRAINT ck_market_policy_fields CHECK ((
    policy - ARRAY['maximum_age_ms', 'maximum_skew_ms', 'maximum_spread_bps', 'maximum_jump_bps', 'recovery_samples', 'recovery_window_ms'] = '{}'::jsonb
    AND jsonb_typeof(policy->'maximum_age_ms') = 'number'
    AND (policy->>'maximum_age_ms') ~ '^[1-9][0-9]{0,3}$'
    AND (policy->>'maximum_age_ms')::numeric BETWEEN 1 AND 5000
    AND jsonb_typeof(COALESCE(policy->'maximum_skew_ms', '0'::jsonb)) = 'number'
    AND COALESCE(policy->>'maximum_skew_ms', '0') ~ '^[0-9]{1,4}$'
    AND COALESCE(policy->>'maximum_skew_ms', '0')::numeric BETWEEN 0 AND 1000
    AND jsonb_typeof(policy->'maximum_spread_bps') = 'string'
    AND (policy->>'maximum_spread_bps') ~ '^[0-9]{1,5}([.][0-9]{1,18})?$'
    AND (policy->>'maximum_spread_bps')::numeric > 0 AND (policy->>'maximum_spread_bps')::numeric <= 10000
    AND jsonb_typeof(policy->'maximum_jump_bps') = 'string'
    AND (policy->>'maximum_jump_bps') ~ '^[0-9]{1,5}([.][0-9]{1,18})?$'
    AND (policy->>'maximum_jump_bps')::numeric > 0 AND (policy->>'maximum_jump_bps')::numeric <= 10000
    AND jsonb_typeof(policy->'recovery_samples') = 'number'
    AND (policy->>'recovery_samples') ~ '^[0-9]{1,2}$'
    AND (policy->>'recovery_samples')::numeric BETWEEN 2 AND 20
    AND jsonb_typeof(COALESCE(policy->'recovery_window_ms', '0'::jsonb)) = 'number'
    AND COALESCE(policy->>'recovery_window_ms', '0') ~ '^[0-9]{1,4}$'
    AND COALESCE(policy->>'recovery_window_ms', '0')::numeric >= 0
    AND COALESCE(policy->>'recovery_window_ms', '0')::numeric < (policy->>'maximum_age_ms')::numeric
) IS TRUE);

CREATE TABLE market_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    market_feed_id bigint NOT NULL REFERENCES market_feeds(id),
    publisher_owner_id varchar(128) NOT NULL CHECK (length(publisher_owner_id) > 0),
    publisher_epoch bigint NOT NULL CHECK (publisher_epoch > 0),
    revision bigint NOT NULL CHECK (revision > 0),
    connection bigint NOT NULL CHECK (connection >= 0),
    generation bigint NOT NULL CHECK (generation >= 0),
    sequence bigint NOT NULL CHECK (sequence >= 0),
    quality varchar(32) NOT NULL,
    reason varchar(32) NOT NULL,
    bid_price numeric(38,18) NOT NULL CHECK (bid_price >= 0 AND bid_price <> 'NaN'::numeric),
    bid_quantity numeric(38,18) NOT NULL CHECK (bid_quantity >= 0 AND bid_quantity <> 'NaN'::numeric),
    ask_price numeric(38,18) NOT NULL CHECK (ask_price >= 0 AND ask_price <> 'NaN'::numeric),
    ask_quantity numeric(38,18) NOT NULL CHECK (ask_quantity >= 0 AND ask_quantity <> 'NaN'::numeric),
    mid_price numeric(76,36) NOT NULL CHECK (mid_price >= 0 AND mid_price <> 'NaN'::numeric),
    event_at bigint NOT NULL CHECK (event_at >= 0),
    received_at bigint NOT NULL CHECK (received_at >= 0),
    evaluated_at bigint NOT NULL CHECK (evaluated_at > 0),
    valid_until bigint NOT NULL CHECK (valid_until >= 0),
    baseline_mid numeric(76,36) NOT NULL CHECK (baseline_mid >= 0 AND baseline_mid <> 'NaN'::numeric),
    baseline_at bigint NOT NULL CHECK (baseline_at >= 0),
    CONSTRAINT uk_market_snapshot_feed UNIQUE (market_feed_id),
    CONSTRAINT ck_market_baseline CHECK ((baseline_mid = 0 AND baseline_at = 0) OR (baseline_mid > 0 AND baseline_at > 0)),
    CONSTRAINT ck_market_quality_reason CHECK (
        (quality = 'HEALTHY' AND reason = '') OR
        (quality = 'UNAVAILABLE' AND reason IN ('SYNCHRONIZING', 'DISCONNECTED')) OR
        (quality = 'WARMING' AND reason = 'RECOVERY_SAMPLES') OR
        (quality = 'INVALID' AND reason IN ('SEQUENCE', 'PAYLOAD', 'OVERFLOW')) OR
        (quality = 'STALE' AND reason = 'AGE') OR
        (quality = 'OUTLIER' AND reason = 'PRICE_JUMP') OR
        (quality = 'WIDE_SPREAD' AND reason = 'SPREAD') OR
        (quality = 'TIME_SKEW' AND reason IN ('FUTURE_TIME', 'CLOCK_REVERSED'))
    ),
    CONSTRAINT ck_market_reference CHECK (
        (quality = 'HEALTHY' AND connection > 0 AND generation > 0 AND bid_price > 0 AND ask_price > bid_price
            AND bid_quantity > 0 AND ask_quantity > 0 AND mid_price * 2 = bid_price + ask_price
            AND event_at > 0 AND received_at > 0 AND valid_until > 0 AND baseline_mid = mid_price AND baseline_at = evaluated_at)
        OR (quality <> 'HEALTHY' AND bid_price = 0 AND ask_price = 0 AND mid_price = 0 AND bid_quantity = 0 AND ask_quantity = 0)
    )
);

CREATE FUNCTION keep_market_snapshot_order() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    jump_limit numeric;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'market snapshot identity and baseline must be retained';
    END IF;
    IF NEW.market_feed_id <> OLD.market_feed_id OR NEW.revision <> OLD.revision + 1 OR NEW.publisher_epoch < OLD.publisher_epoch
        OR NEW.delete_at IS NOT NULL OR NEW.create_at <> OLD.create_at THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'market snapshot revision or identity rejected';
    END IF;
    IF NEW.publisher_epoch = OLD.publisher_epoch AND (
        NEW.publisher_owner_id <> OLD.publisher_owner_id OR NEW.connection < OLD.connection OR
        (NEW.connection = OLD.connection AND (NEW.generation < OLD.generation OR (NEW.generation = OLD.generation AND NEW.sequence < OLD.sequence)))
    ) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'market snapshot sequence regressed', CONSTRAINT = 'market_snapshot_sequence';
    END IF;
    IF NEW.publisher_epoch = OLD.publisher_epoch AND NEW.connection = OLD.connection AND NEW.generation = OLD.generation AND NEW.sequence = OLD.sequence
        AND NEW.quality = 'HEALTHY' AND OLD.quality = 'HEALTHY'
        AND ROW(NEW.bid_price, NEW.ask_price, NEW.bid_quantity, NEW.ask_quantity, NEW.mid_price)
            IS DISTINCT FROM ROW(OLD.bid_price, OLD.ask_price, OLD.bid_quantity, OLD.ask_quantity, OLD.mid_price) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'same market sequence changed prices', CONSTRAINT = 'market_snapshot_sequence';
    END IF;
    IF NEW.quality <> 'HEALTHY' AND ROW(NEW.baseline_mid, NEW.baseline_at) IS DISTINCT FROM ROW(OLD.baseline_mid, OLD.baseline_at) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'unaccepted market value cannot change baseline';
    END IF;
    IF NEW.quality = 'HEALTHY' AND OLD.baseline_mid > 0 THEN
        SELECT (policy->>'maximum_jump_bps')::numeric INTO jump_limit FROM market_feeds WHERE id = OLD.market_feed_id;
        IF abs(NEW.mid_price - OLD.baseline_mid) * 10000 > OLD.baseline_mid * jump_limit THEN
            RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'persisted market baseline jump rejected';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER market_snapshot_order BEFORE UPDATE OR DELETE ON market_snapshots
    FOR EACH ROW EXECUTE FUNCTION keep_market_snapshot_order();

CREATE FUNCTION validate_market_publication() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    feed market_feeds%ROWTYPE;
    lease market_publisher_leases%ROWTYPE;
    now_ms bigint;
    age_ms bigint;
    skew_ms bigint;
BEGIN
    SELECT * INTO feed FROM market_feeds WHERE id = NEW.market_feed_id FOR SHARE;
    SELECT * INTO lease FROM market_publisher_leases WHERE market_feed_id = NEW.market_feed_id FOR UPDATE;
    now_ms := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
    IF feed.id IS NULL OR feed.delete_at IS NOT NULL OR lease.id IS NULL OR lease.delete_at IS NOT NULL
        OR lease.owner_id <> NEW.publisher_owner_id OR lease.epoch <> NEW.publisher_epoch OR lease.expires_at <= now_ms
        OR NEW.delete_at IS NOT NULL THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'market publisher authority rejected', CONSTRAINT = 'market_snapshot_fence';
    END IF;
    IF NEW.quality = 'HEALTHY' THEN
        age_ms := (feed.policy->>'maximum_age_ms')::bigint;
        skew_ms := COALESCE(feed.policy->>'maximum_skew_ms', '0')::bigint;
        IF NEW.valid_until <= now_ms OR NEW.valid_until > LEAST(NEW.event_at + age_ms, NEW.received_at + age_ms, lease.expires_at)
            OR NEW.event_at > now_ms + skew_ms OR NEW.received_at > now_ms + skew_ms OR NEW.evaluated_at > now_ms + skew_ms
            OR now_ms - NEW.event_at >= age_ms OR now_ms - NEW.received_at >= age_ms
            OR (NEW.ask_price - NEW.bid_price) * 10000 > NEW.mid_price * (feed.policy->>'maximum_spread_bps')::numeric THEN
            RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'market quote quality rejected at commit', CONSTRAINT = 'market_snapshot_quality';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE CONSTRAINT TRIGGER market_snapshot_fence AFTER INSERT OR UPDATE ON market_snapshots
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_market_publication();

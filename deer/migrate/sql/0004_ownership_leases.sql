CREATE TABLE strategy_leases (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    strategy_instance_id bigint NOT NULL REFERENCES strategy_instances(id),
    owner_id varchar(128) NOT NULL,
    epoch bigint NOT NULL CHECK (epoch >= 0),
    expires_at bigint NOT NULL CHECK (expires_at >= 0),
    CONSTRAINT uk_strategy_lease_instance UNIQUE (strategy_instance_id),
    CONSTRAINT ck_strategy_lease_owner CHECK ((epoch = 0 AND owner_id = '' AND expires_at = 0) OR (epoch > 0 AND length(owner_id) > 0))
);
CREATE TABLE execution_shard_leases (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    account_id varchar(64) NOT NULL CHECK (length(account_id) > 0),
    owner_id varchar(128) NOT NULL,
    epoch bigint NOT NULL CHECK (epoch >= 0),
    expires_at bigint NOT NULL CHECK (expires_at >= 0),
    CONSTRAINT uk_execution_lease_account UNIQUE (account_id),
    CONSTRAINT ck_execution_lease_owner CHECK ((epoch = 0 AND owner_id = '' AND expires_at = 0) OR (epoch > 0 AND length(owner_id) > 0))
);

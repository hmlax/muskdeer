CREATE TABLE account_budgets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    account_id varchar(64) NOT NULL CHECK (length(account_id) > 0),
    asset varchar(32) NOT NULL CHECK (length(asset) > 0),
    limit_notional numeric(76,36) NOT NULL CHECK (limit_notional > 0 AND limit_notional <> 'NaN'::numeric),
    reserved_notional numeric(76,36) NOT NULL CHECK (reserved_notional >= 0 AND reserved_notional <= limit_notional AND reserved_notional <> 'NaN'::numeric),
    enabled boolean NOT NULL,
    revision bigint NOT NULL CHECK (revision > 0),
    CONSTRAINT uk_account_budget_account UNIQUE (account_id)
);
CREATE TABLE strategy_budgets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    strategy_instance_id bigint NOT NULL,
    account_id varchar(64) NOT NULL REFERENCES account_budgets(account_id),
    limit_notional numeric(76,36) NOT NULL CHECK (limit_notional > 0 AND limit_notional <> 'NaN'::numeric),
    reserved_notional numeric(76,36) NOT NULL CHECK (reserved_notional >= 0 AND reserved_notional <= limit_notional AND reserved_notional <> 'NaN'::numeric),
    enabled boolean NOT NULL,
    revision bigint NOT NULL CHECK (revision > 0),
    CONSTRAINT uk_strategy_budget_instance UNIQUE (strategy_instance_id),
    CONSTRAINT fk_strategy_budget_account FOREIGN KEY (strategy_instance_id, account_id) REFERENCES strategy_instances(id, account_id)
);
CREATE TABLE risk_snapshots (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    strategy_instance_id bigint NOT NULL,
    account_id varchar(64) NOT NULL,
    instrument_id bigint NOT NULL REFERENCES instruments(id),
    config_version bigint NOT NULL,
    market_data_source varchar(32) NOT NULL CHECK (market_data_source IN ('binance', 'okx')),
    market_epoch bigint NOT NULL CHECK (market_epoch > 0),
    market_sequence bigint NOT NULL CHECK (market_sequence > 0),
    observed_at bigint NOT NULL CHECK (observed_at > 0),
    expires_at bigint NOT NULL CHECK (expires_at > observed_at AND expires_at - observed_at <= 5000),
    reconciled boolean NOT NULL,
    allow_new_risk boolean NOT NULL,
    revision bigint NOT NULL CHECK (revision > 0),
    CONSTRAINT uk_risk_snapshot_instance UNIQUE (strategy_instance_id),
    CONSTRAINT fk_risk_snapshot_account FOREIGN KEY (strategy_instance_id, account_id) REFERENCES strategy_instances(id, account_id),
    CONSTRAINT fk_risk_snapshot_config FOREIGN KEY (strategy_instance_id, config_version) REFERENCES strategy_config_versions(instance_id, version)
);
CREATE TABLE order_intents (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    account_id varchar(64) NOT NULL REFERENCES account_budgets(account_id),
    idempotency_key varchar(128) NOT NULL CHECK (length(idempotency_key) > 0),
    client_order_id varchar(64) NOT NULL CHECK (length(client_order_id) > 0),
    strategy_instance_id bigint NOT NULL,
    config_version bigint NOT NULL,
    instrument_id bigint NOT NULL REFERENCES instruments(id),
    request_id varchar(64) NOT NULL,
    fingerprint char(64) NOT NULL CHECK (fingerprint ~ '^[0-9a-f]{64}$'),
    side varchar(8) NOT NULL CHECK (side IN ('BUY', 'SELL')),
    price numeric(38,18) NOT NULL CHECK (price > 0 AND price <> 'NaN'::numeric),
    quantity numeric(38,18) NOT NULL CHECK (quantity > 0 AND quantity <> 'NaN'::numeric),
    filled_quantity numeric(38,18) NOT NULL CHECK (filled_quantity >= 0 AND filled_quantity <= quantity AND filled_quantity <> 'NaN'::numeric),
    reserved_quote_notional numeric(76,36) NOT NULL CHECK (reserved_quote_notional >= 0 AND reserved_quote_notional <> 'NaN'::numeric),
    time_in_force varchar(16) NOT NULL CHECK (time_in_force IN ('GTC', 'IOC', 'POST_ONLY')),
    reduce_only boolean NOT NULL,
    state varchar(32) NOT NULL CHECK (state IN ('INTENT', 'SUBMITTING', 'LIVE', 'PARTIALLY_FILLED', 'FILLED', 'CANCELED', 'REJECTED', 'UNKNOWN')),
    cancel_state varchar(16) NOT NULL CHECK (cancel_state IN ('NONE', 'REQUESTED', 'PENDING', 'CONFIRMED', 'UNKNOWN', 'REJECTED')),
    core_order_id bigint NULL CHECK (core_order_id > 0),
    owner_id varchar(128) NOT NULL CHECK (length(owner_id) > 0),
    owner_epoch bigint NOT NULL CHECK (owner_epoch > 0),
    execution_owner_id varchar(128) NOT NULL CHECK (length(execution_owner_id) > 0),
    execution_epoch bigint NOT NULL CHECK (execution_epoch > 0),
    submission_deadline_at bigint NOT NULL CHECK (submission_deadline_at > 0),
    revision bigint NOT NULL CHECK (revision > 0),
    error_code varchar(64) NOT NULL,
    CONSTRAINT uk_order_intent_account_key UNIQUE (account_id, idempotency_key),
    CONSTRAINT uk_order_intent_account_client UNIQUE (account_id, client_order_id),
    CONSTRAINT fk_order_intent_strategy_account FOREIGN KEY (strategy_instance_id, account_id) REFERENCES strategy_instances(id, account_id),
    CONSTRAINT fk_order_intent_config FOREIGN KEY (strategy_instance_id, config_version) REFERENCES strategy_config_versions(instance_id, version),
    CONSTRAINT ck_terminal_intent_reserve CHECK (state NOT IN ('FILLED', 'CANCELED', 'REJECTED') OR reserved_quote_notional = 0)
);
CREATE INDEX idx_order_intent_strategy ON order_intents(strategy_instance_id);
CREATE TABLE outbox_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    event_id varchar(128) NOT NULL,
    intent_id bigint NOT NULL REFERENCES order_intents(id),
    event_type varchar(64) NOT NULL,
    event jsonb NOT NULL CHECK (jsonb_typeof(event) = 'object'),
    state varchar(16) NOT NULL CHECK (state IN ('PENDING', 'PUBLISHING', 'PUBLISHED', 'FAILED')),
    attempts bigint NOT NULL CHECK (attempts >= 0),
    next_attempt_at bigint NOT NULL CHECK (next_attempt_at >= 0),
    claimed_by varchar(128) NOT NULL,
    claim_expires_at bigint NOT NULL CHECK (claim_expires_at >= 0),
    published_at bigint NULL,
    error_code varchar(64) NOT NULL,
    CONSTRAINT uk_outbox_event_id UNIQUE (event_id),
    CONSTRAINT ck_outbox_typed_payload CHECK (
        (event_type IN ('OrderIntentAccepted', 'OrderStateChanged') AND jsonb_typeof(event->'intent') IS NOT DISTINCT FROM 'object' AND NOT (event ? 'fill'))
        OR (event_type = 'TradeFilled' AND jsonb_typeof(event->'fill') IS NOT DISTINCT FROM 'object' AND NOT (event ? 'intent'))
    ),
    CONSTRAINT ck_outbox_identity CHECK (event->>'event_id' IS NOT DISTINCT FROM event_id AND event->>'event_type' IS NOT DISTINCT FROM event_type)
);
CREATE INDEX idx_outbox_intent ON outbox_events(intent_id);
CREATE INDEX idx_outbox_state_id ON outbox_events(state, id);

-- Immutable scope acceptance is separate from later bounded execution progress.
CREATE TABLE admin_emergency_cancellations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL CHECK (delete_at IS NULL),
    actor_user_id bigint NOT NULL REFERENCES admin_users(id),
    actor_session_id bigint NOT NULL REFERENCES admin_sessions(id),
    strategy_instance_id bigint NOT NULL REFERENCES strategy_instances(id),
    risk_change_id bigint NOT NULL CONSTRAINT uk_admin_emergency_cancellation_risk UNIQUE REFERENCES admin_strategy_risk_changes(id),
    audit_id bigint NOT NULL CONSTRAINT uk_admin_emergency_cancellation_audit UNIQUE REFERENCES admin_audits(id),
    idempotency_key varchar(64) NOT NULL CHECK (idempotency_key ~ '^[A-Za-z0-9_.:-]{16,64}$'),
    request_fingerprint char(64) NOT NULL CHECK (request_fingerprint ~ '^[0-9a-f]{64}$'),
    scope varchar(16) NOT NULL CHECK (scope = 'strategy'),
    expected_risk_revision bigint NOT NULL CHECK (expected_risk_revision > 0 AND expected_risk_revision < 9223372036854775807),
    risk_revision bigint NOT NULL CHECK (risk_revision > expected_risk_revision AND risk_revision - expected_risk_revision = 1),
    reason varchar(256) NOT NULL CHECK (length(reason) > 0 AND octet_length(reason) <= 256),
    CONSTRAINT uk_admin_emergency_cancellation_key UNIQUE (actor_user_id, idempotency_key)
);
CREATE INDEX idx_admin_emergency_cancellation_strategy ON admin_emergency_cancellations(strategy_instance_id, id);

CREATE FUNCTION keep_admin_emergency_cancellation_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_emergency_history', MESSAGE = 'emergency acceptance history is immutable';
END;
$$;
CREATE TRIGGER admin_emergency_cancellation_history BEFORE UPDATE OR DELETE ON admin_emergency_cancellations
    FOR EACH ROW EXECUTE FUNCTION keep_admin_emergency_cancellation_history();

CREATE FUNCTION guard_admin_emergency_cancellation() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    principal admin_users%ROWTYPE;
    session admin_sessions%ROWTYPE;
    strategy strategy_instances%ROWTYPE;
    budget strategy_budgets%ROWTYPE;
    risk admin_strategy_risk_changes%ROWTYPE;
    audit admin_audits%ROWTYPE;
    current_risk_revision bigint;
    now_ms bigint;
BEGIN
    SELECT * INTO principal FROM admin_users WHERE id = NEW.actor_user_id FOR SHARE;
    SELECT * INTO session FROM admin_sessions WHERE id = NEW.actor_session_id FOR SHARE;
    SELECT * INTO strategy FROM strategy_instances WHERE id = NEW.strategy_instance_id FOR SHARE;
    SELECT * INTO budget FROM strategy_budgets WHERE strategy_instance_id = NEW.strategy_instance_id FOR SHARE;
    now_ms := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
    IF principal.id IS NULL OR session.id IS NULL OR NOT principal.enabled OR principal.delete_at IS NOT NULL OR
       principal.role NOT IN ('operator', 'admin') OR session.user_id <> principal.id OR session.delete_at IS NOT NULL OR
       session.revoked_at IS NOT NULL OR session.credential_version <> principal.credential_version OR session.expires_at <= now_ms THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_emergency_authority', MESSAGE = 'emergency acceptance requires current authority';
    END IF;
    SELECT * INTO risk FROM admin_strategy_risk_changes WHERE id = NEW.risk_change_id;
    SELECT COALESCE(max(revision), 1) INTO current_risk_revision FROM admin_strategy_risk_changes WHERE strategy_instance_id = NEW.strategy_instance_id;
    IF strategy.id IS NULL OR strategy.delete_at IS NOT NULL OR budget.id IS NULL OR budget.delete_at IS NOT NULL OR
       budget.account_id <> strategy.account_id OR budget.enabled OR risk.id IS NULL OR risk.delete_at IS NOT NULL OR
       risk.actor_user_id <> principal.id OR risk.actor_session_id <> session.id OR risk.strategy_instance_id <> strategy.id OR
       risk.action <> 'risk.strategy.block' OR risk.enabled OR risk.previous_revision <> NEW.expected_risk_revision OR
       risk.revision <> NEW.risk_revision OR risk.reason <> NEW.reason OR current_risk_revision <> NEW.risk_revision OR
       EXISTS (SELECT 1 FROM risk_snapshots WHERE strategy_instance_id = strategy.id AND delete_at IS NULL AND allow_new_risk) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_emergency_scope', MESSAGE = 'emergency acceptance requires its current scoped risk block';
    END IF;
    SELECT * INTO audit FROM admin_audits WHERE id = NEW.audit_id;
    IF audit.id IS NULL OR audit.delete_at IS NOT NULL OR audit.actor <> principal.username OR audit.actor_role <> principal.role OR
       audit.action <> 'strategy.emergency_cancel' OR audit.resource <> 'strategy_instance:' || strategy.id::text OR
       audit.reason <> NEW.reason OR audit.before_version IS DISTINCT FROM NEW.expected_risk_revision OR
       audit.after_version IS DISTINCT FROM NEW.risk_revision THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_emergency_audit', MESSAGE = 'emergency acceptance requires its scoped audit';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER admin_emergency_cancellation_commit AFTER INSERT ON admin_emergency_cancellations
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION guard_admin_emergency_cancellation();

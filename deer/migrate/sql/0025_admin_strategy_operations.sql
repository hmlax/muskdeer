CREATE TABLE admin_strategy_operations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL CHECK (delete_at IS NULL),
    actor_user_id bigint NOT NULL REFERENCES admin_users(id),
    actor_session_id bigint NOT NULL REFERENCES admin_sessions(id),
    strategy_instance_id bigint NOT NULL REFERENCES strategy_instances(id),
    audit_id bigint NOT NULL CONSTRAINT uk_admin_strategy_operation_audit UNIQUE REFERENCES admin_audits(id),
    idempotency_key varchar(64) NOT NULL CHECK (idempotency_key ~ '^[A-Za-z0-9_.:-]{16,64}$'),
    request_fingerprint char(64) NOT NULL CHECK (request_fingerprint ~ '^[0-9a-f]{64}$'),
    action varchar(32) NOT NULL CHECK (action IN ('strategy.start', 'strategy.resume', 'strategy.pause', 'strategy.stop')),
    target_state varchar(16) NOT NULL CHECK (
        (action IN ('strategy.start', 'strategy.resume') AND target_state = 'RUNNING') OR
        (action = 'strategy.pause' AND target_state = 'PAUSED') OR
        (action = 'strategy.stop' AND target_state = 'STOPPED')),
    expected_revision bigint NOT NULL CHECK (expected_revision > 0 AND expected_revision < 9223372036854775807),
    effect_revision bigint NOT NULL CHECK (effect_revision = expected_revision + 1),
    config_version bigint NOT NULL CHECK (config_version > 0),
    market_data_source varchar(32) NOT NULL CHECK (market_data_source IN ('binance', 'okx')),
    reason varchar(256) NOT NULL CHECK (length(reason) > 0),
    state varchar(16) NOT NULL CHECK (state IN ('ACCEPTED', 'SUCCEEDED', 'SUPERSEDED')),
    outcome_code varchar(32) NOT NULL,
    revision bigint NOT NULL,
    completed_at bigint NULL,
    observed_revision bigint NULL,
    observed_state varchar(32) NULL,
    observed_owner_id varchar(128) NULL,
    observed_owner_epoch bigint NULL,
    CONSTRAINT uk_admin_strategy_operation_key UNIQUE (actor_user_id, idempotency_key),
    CONSTRAINT ck_admin_strategy_operation_shape CHECK (
        (state = 'ACCEPTED' AND outcome_code = 'pending' AND revision = 1 AND completed_at IS NULL AND
         observed_revision IS NULL AND observed_state IS NULL AND observed_owner_id IS NULL AND observed_owner_epoch IS NULL) OR
        (state IN ('SUCCEEDED', 'SUPERSEDED') AND revision = 2 AND completed_at IS NOT NULL AND completed_at >= create_at AND
         observed_revision IS NOT NULL AND observed_revision >= effect_revision AND observed_state IS NOT NULL AND
         observed_owner_id IS NOT NULL AND observed_owner_epoch IS NOT NULL AND observed_owner_epoch >= 0 AND
         ((state = 'SUCCEEDED' AND outcome_code = 'target_reached') OR (state = 'SUPERSEDED' AND outcome_code = 'target_replaced'))))
);
CREATE INDEX idx_admin_strategy_operation_strategy ON admin_strategy_operations(strategy_instance_id);
CREATE INDEX idx_admin_strategy_operation_pending ON admin_strategy_operations(state);

CREATE FUNCTION guard_admin_strategy_operation() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    principal admin_users%ROWTYPE;
    session admin_sessions%ROWTYPE;
    audit admin_audits%ROWTYPE;
    strategy strategy_instances%ROWTYPE;
    lease strategy_leases%ROWTYPE;
    now_ms bigint;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_operation_history', MESSAGE = 'operation history must be retained';
    END IF;
    IF TG_OP = 'INSERT' THEN
        IF NEW.state <> 'ACCEPTED' OR NEW.revision <> 1 THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_operation_history', MESSAGE = 'operations begin accepted';
        END IF;
        SELECT * INTO principal FROM admin_users WHERE id = NEW.actor_user_id FOR SHARE;
        SELECT * INTO session FROM admin_sessions WHERE id = NEW.actor_session_id FOR SHARE;
        now_ms := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
        IF principal.id IS NULL OR session.id IS NULL OR NOT principal.enabled OR principal.delete_at IS NOT NULL OR
           principal.role NOT IN ('operator', 'admin') OR session.user_id <> principal.id OR session.delete_at IS NOT NULL OR
           session.revoked_at IS NOT NULL OR session.credential_version <> principal.credential_version OR session.expires_at <= now_ms THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_operation_authority', MESSAGE = 'operation requires current operator authority';
        END IF;
        SELECT * INTO audit FROM admin_audits WHERE id = NEW.audit_id;
        IF audit.id IS NULL OR audit.delete_at IS NOT NULL OR audit.actor <> principal.username OR audit.actor_role <> principal.role OR audit.action <> NEW.action OR
           audit.resource <> 'strategy_instance:' || NEW.strategy_instance_id::text OR audit.reason <> NEW.reason OR
           audit.before_version IS DISTINCT FROM NEW.expected_revision OR audit.after_version IS DISTINCT FROM NEW.effect_revision THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_operation_audit', MESSAGE = 'operation requires matching immutable audit';
        END IF;
    ELSE
        IF ROW(NEW.id, NEW.create_at, NEW.delete_at, NEW.actor_user_id, NEW.actor_session_id, NEW.strategy_instance_id, NEW.audit_id,
            NEW.idempotency_key, NEW.request_fingerprint, NEW.action, NEW.target_state, NEW.expected_revision, NEW.effect_revision,
            NEW.config_version, NEW.market_data_source, NEW.reason) IS DISTINCT FROM
           ROW(OLD.id, OLD.create_at, OLD.delete_at, OLD.actor_user_id, OLD.actor_session_id, OLD.strategy_instance_id, OLD.audit_id,
            OLD.idempotency_key, OLD.request_fingerprint, OLD.action, OLD.target_state, OLD.expected_revision, OLD.effect_revision,
            OLD.config_version, OLD.market_data_source, OLD.reason) OR
           (OLD.state <> 'ACCEPTED' AND NEW IS DISTINCT FROM OLD) OR
           (OLD.state = 'ACCEPTED' AND NEW.state = 'ACCEPTED' AND NEW IS DISTINCT FROM OLD) THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_operation_history', MESSAGE = 'operation identity and terminal facts are immutable';
        END IF;
    END IF;
    SELECT * INTO strategy FROM strategy_instances WHERE id = NEW.strategy_instance_id FOR SHARE;
    now_ms := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
    IF strategy.id IS NULL THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_operation_request', MESSAGE = 'operation requires a current strategy';
    END IF;
    IF TG_OP = 'INSERT' THEN
        IF session.expires_at <= now_ms THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_operation_authority', MESSAGE = 'operation session expired while waiting';
        END IF;
        IF strategy.delete_at IS NOT NULL OR strategy.revision <> NEW.effect_revision OR strategy.desired_state <> NEW.target_state OR
           strategy.requested_config_version <> NEW.config_version OR strategy.market_data_source <> NEW.market_data_source THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_operation_request', MESSAGE = 'operation does not match accepted revision and intent';
        END IF;
        RETURN NEW;
    END IF;
    IF NEW.state = 'ACCEPTED' THEN RETURN NEW; END IF;
    IF NEW.observed_revision IS DISTINCT FROM strategy.revision OR NEW.observed_state IS DISTINCT FROM strategy.state OR
       NEW.observed_owner_id IS DISTINCT FROM strategy.runtime_owner_id OR NEW.observed_owner_epoch IS DISTINCT FROM strategy.runtime_owner_epoch OR
       NEW.completed_at > now_ms THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_operation_observation', MESSAGE = 'operation result requires current runtime observation';
    END IF;
    IF NEW.state = 'SUPERSEDED' THEN
        IF strategy.delete_at IS NULL AND ROW(strategy.desired_state, strategy.requested_config_version, strategy.market_data_source) IS NOT DISTINCT FROM
           ROW(NEW.target_state, NEW.config_version, NEW.market_data_source) THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_operation_observation', MESSAGE = 'operation target has not been replaced';
        END IF;
        RETURN NEW;
    END IF;
    IF strategy.delete_at IS NOT NULL OR strategy.state <> NEW.target_state OR strategy.desired_state <> NEW.target_state OR
       strategy.requested_config_version <> NEW.config_version OR strategy.market_data_source <> NEW.market_data_source THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_operation_observation', MESSAGE = 'operation target has not completed';
    END IF;
    IF NEW.target_state = 'RUNNING' THEN
        SELECT * INTO lease FROM strategy_leases WHERE strategy_instance_id = strategy.id AND delete_at IS NULL FOR SHARE;
        now_ms := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
        IF strategy.runtime_owner_epoch <= 0 OR strategy.active_config_version IS DISTINCT FROM NEW.config_version OR
           strategy.active_market_data_source IS DISTINCT FROM NEW.market_data_source OR lease.id IS NULL OR
           lease.owner_id <> strategy.runtime_owner_id OR lease.epoch <> strategy.runtime_owner_epoch OR lease.expires_at <= now_ms THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_operation_lease_not_ready', MESSAGE = 'running operation requires its current fenced owner';
        END IF;
    ELSIF strategy_has_obligations(strategy.id) OR EXISTS (
        SELECT 1 FROM strategy_budgets WHERE strategy_instance_id = strategy.id AND delete_at IS NULL AND reserved_notional <> 0) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_operation_observation', MESSAGE = 'terminal operation retains unresolved obligations';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER admin_strategy_operation_guard BEFORE INSERT OR UPDATE OR DELETE ON admin_strategy_operations
    FOR EACH ROW EXECUTE FUNCTION guard_admin_strategy_operation();

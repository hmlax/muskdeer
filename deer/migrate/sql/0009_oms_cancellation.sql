ALTER TABLE order_intents ADD CONSTRAINT uk_order_intent_cancel_target UNIQUE (id, account_id, client_order_id);
CREATE TABLE cancellation_requests (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    account_id varchar(64) NOT NULL,
    idempotency_key varchar(128) NOT NULL CHECK (length(idempotency_key) > 0),
    intent_id bigint NOT NULL,
    client_order_id varchar(64) NOT NULL,
    strategy_instance_id bigint NOT NULL,
    instrument_id bigint NOT NULL REFERENCES instruments(id),
    config_version bigint NOT NULL,
    owner_id varchar(128) NOT NULL CHECK (length(owner_id) > 0),
    owner_epoch bigint NOT NULL CHECK (owner_epoch > 0),
    execution_owner_id varchar(128) NOT NULL CHECK (length(execution_owner_id) > 0),
    execution_epoch bigint NOT NULL CHECK (execution_epoch > 0),
    core_command_key varchar(128) NOT NULL CHECK (length(core_command_key) > 0),
    state varchar(16) NOT NULL CHECK (state IN ('REQUESTED', 'SUBMITTING', 'PENDING', 'CONFIRMED', 'UNKNOWN', 'REJECTED')),
    deadline_at bigint NOT NULL CHECK (deadline_at > 0),
    revision bigint NOT NULL CHECK (revision > 0),
    error_code varchar(64) NOT NULL,
    request_id varchar(64) NOT NULL,
    CONSTRAINT uk_cancellation_account_key UNIQUE (account_id, idempotency_key),
    CONSTRAINT fk_cancellation_target FOREIGN KEY (intent_id, account_id, client_order_id) REFERENCES order_intents(id, account_id, client_order_id),
    CONSTRAINT fk_cancellation_strategy FOREIGN KEY (strategy_instance_id, account_id) REFERENCES strategy_instances(id, account_id),
    CONSTRAINT fk_cancellation_config FOREIGN KEY (strategy_instance_id, config_version) REFERENCES strategy_config_versions(instance_id, version)
);
CREATE INDEX idx_cancellation_intent ON cancellation_requests(intent_id);
ALTER TABLE outbox_events DROP CONSTRAINT ck_outbox_typed_payload;
ALTER TABLE outbox_events ADD CONSTRAINT ck_outbox_typed_payload CHECK (
    (event_type IN ('OrderIntentAccepted', 'OrderStateChanged') AND jsonb_typeof(event->'intent') IS NOT DISTINCT FROM 'object'
        AND NOT (event ? 'fill') AND NOT (event ? 'cancellation'))
    OR (event_type = 'TradeFilled' AND jsonb_typeof(event->'fill') IS NOT DISTINCT FROM 'object'
        AND NOT (event ? 'intent') AND NOT (event ? 'cancellation'))
    OR (event_type IN ('OrderCancelRequested', 'OrderCancelStateChanged') AND jsonb_typeof(event->'cancellation') IS NOT DISTINCT FROM 'object'
        AND NOT (event ? 'intent') AND NOT (event ? 'fill'))
);

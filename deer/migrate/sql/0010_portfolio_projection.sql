CREATE TABLE portfolio_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    account_id varchar(64) NOT NULL REFERENCES simulator_accounts(account_id),
    instrument_id bigint NOT NULL REFERENCES instruments(id),
    base_asset varchar(32) NOT NULL,
    quote_asset varchar(32) NOT NULL,
    opening_quantity numeric(76,36) NOT NULL CHECK (opening_quantity >= 0 AND opening_quantity <> 'NaN'::numeric),
    opening_cash_quote numeric(76,36) NOT NULL CHECK (opening_cash_quote >= 0 AND opening_cash_quote <> 'NaN'::numeric),
    opening_cost_quote numeric(76,36) NOT NULL CHECK (opening_cost_quote >= 0 AND opening_cost_quote <> 'NaN'::numeric),
    quantity numeric(76,36) NOT NULL CHECK (quantity >= 0 AND quantity <> 'NaN'::numeric),
    cash_quote numeric(76,36) NOT NULL CHECK (cash_quote >= 0 AND cash_quote <> 'NaN'::numeric),
    cost_quote numeric(76,36) NOT NULL CHECK (cost_quote >= 0 AND cost_quote <> 'NaN'::numeric),
    realized_pnl_quote numeric(76,36) NOT NULL CHECK (realized_pnl_quote <> 'NaN'::numeric),
    fees_quote numeric(76,36) NOT NULL CHECK (fees_quote >= 0 AND fees_quote <> 'NaN'::numeric),
    last_source_sequence bigint NOT NULL CHECK (last_source_sequence >= 0),
    reconciled boolean NOT NULL,
    revision bigint NOT NULL CHECK (revision > 0),
    error_code varchar(64) NOT NULL,
    CONSTRAINT uk_portfolio_account_key UNIQUE (account_id),
    CONSTRAINT ck_portfolio_opening_cost CHECK (opening_quantity > 0 OR opening_cost_quote = 0)
);
CREATE FUNCTION keep_portfolio_anchor() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF ROW(NEW.account_id, NEW.instrument_id, NEW.base_asset, NEW.quote_asset, NEW.opening_quantity, NEW.opening_cash_quote, NEW.opening_cost_quote)
        IS DISTINCT FROM ROW(OLD.account_id, OLD.instrument_id, OLD.base_asset, OLD.quote_asset, OLD.opening_quantity, OLD.opening_cash_quote, OLD.opening_cost_quote) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'portfolio opening anchor is immutable';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER portfolio_anchor_immutable BEFORE UPDATE ON portfolio_accounts FOR EACH ROW EXECUTE FUNCTION keep_portfolio_anchor();
CREATE TABLE portfolio_fills (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    execution_venue varchar(32) NOT NULL CHECK (execution_venue = 'simulator'),
    trade_id varchar(128) NOT NULL,
    source_sequence bigint NOT NULL REFERENCES simulator_fills(id) CHECK (source_sequence > 0),
    intent_id bigint NOT NULL REFERENCES order_intents(id),
    core_order_id bigint NOT NULL REFERENCES simulator_orders(id),
    account_id varchar(64) NOT NULL REFERENCES portfolio_accounts(account_id),
    strategy_instance_id bigint NOT NULL REFERENCES strategy_instances(id),
    instrument_id bigint NOT NULL REFERENCES instruments(id),
    side varchar(8) NOT NULL CHECK (side IN ('BUY', 'SELL')),
    price numeric(38,18) NOT NULL CHECK (price > 0 AND price <> 'NaN'::numeric),
    quantity numeric(38,18) NOT NULL CHECK (quantity > 0 AND quantity <> 'NaN'::numeric),
    quote_notional numeric(76,36) NOT NULL CHECK (quote_notional = price * quantity AND quote_notional <> 'NaN'::numeric),
    fee_amount numeric(76,36) NOT NULL CHECK (fee_amount >= 0 AND fee_amount < quote_notional AND fee_amount <> 'NaN'::numeric),
    fee_asset varchar(32) NOT NULL,
    CONSTRAINT uk_portfolio_fill_trade UNIQUE (execution_venue, trade_id),
    CONSTRAINT uk_portfolio_fill_sequence UNIQUE (execution_venue, source_sequence)
);
CREATE INDEX idx_portfolio_fill_account_sequence ON portfolio_fills(account_id, source_sequence);
CREATE TRIGGER portfolio_fill_immutable BEFORE UPDATE OR DELETE ON portfolio_fills
    FOR EACH ROW EXECUTE FUNCTION reject_simulator_command_change();
CREATE TABLE consumer_inboxes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    consumer varchar(64) NOT NULL,
    event_id varchar(128) NOT NULL,
    payload_hash char(64) NOT NULL CHECK (payload_hash ~ '^[0-9a-f]{64}$'),
    processed_at bigint NOT NULL CHECK (processed_at > 0),
    CONSTRAINT uk_inbox_consumer_event UNIQUE (consumer, event_id)
);

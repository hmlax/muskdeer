-- Durable enrollment is metadata only. Existing cancellation actions and
-- the final gateway retain all ownership, UNKNOWN and reservation checks.
CREATE TABLE admin_emergency_cancellation_tasks (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL CHECK (delete_at IS NULL),
    emergency_cancellation_id bigint NOT NULL CONSTRAINT uk_admin_emergency_task_batch UNIQUE REFERENCES admin_emergency_cancellations(id),
    strategy_instance_id bigint NOT NULL REFERENCES strategy_instances(id),
    enrollment_upper_id bigint NULL CHECK (enrollment_upper_id >= 0),
    enrollment_after_id bigint NOT NULL CHECK (enrollment_after_id >= 0),
    enrollment_complete boolean NOT NULL,
    state varchar(16) NOT NULL CHECK (state IN ('ACCEPTED', 'SUCCEEDED', 'FAILED')),
    revision bigint NOT NULL CHECK (revision > 0),
    completed_at bigint NULL,
    CONSTRAINT ck_admin_emergency_task_enrollment CHECK (
        (enrollment_upper_id IS NULL AND enrollment_after_id = 0 AND NOT enrollment_complete)
        OR (enrollment_upper_id IS NOT NULL AND enrollment_after_id <= enrollment_upper_id
            AND (NOT enrollment_complete OR enrollment_after_id = enrollment_upper_id))
    ),
    CONSTRAINT ck_admin_emergency_task_result CHECK (
        (state = 'ACCEPTED' AND completed_at IS NULL)
        OR (state <> 'ACCEPTED' AND enrollment_complete AND completed_at IS NOT NULL AND completed_at >= create_at)
    )
);
CREATE INDEX idx_admin_emergency_task_strategy ON admin_emergency_cancellation_tasks(strategy_instance_id, id) WHERE state = 'ACCEPTED';
ALTER TABLE admin_order_cancellations ADD COLUMN emergency_cancellation_id bigint NULL REFERENCES admin_emergency_cancellations(id);
CREATE INDEX idx_admin_cancellation_emergency ON admin_order_cancellations(emergency_cancellation_id);
CREATE UNIQUE INDEX uk_admin_cancellation_emergency_order ON admin_order_cancellations(emergency_cancellation_id, order_intent_id) WHERE emergency_cancellation_id IS NOT NULL;

CREATE FUNCTION guard_admin_emergency_task() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    scope_row admin_emergency_cancellations%ROWTYPE;
    budget strategy_budgets%ROWTYPE;
    actual_upper bigint;
    target_count bigint;
    terminal_count bigint;
    failed_count bigint;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_emergency_task_history', MESSAGE = 'emergency progress cannot be deleted';
    END IF;
    SELECT * INTO scope_row FROM admin_emergency_cancellations WHERE id = NEW.emergency_cancellation_id;
    IF scope_row.id IS NULL OR scope_row.strategy_instance_id <> NEW.strategy_instance_id THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_emergency_task_scope', MESSAGE = 'progress requires its accepted strategy scope';
    END IF;
    IF TG_OP = 'INSERT' THEN
        IF NEW.state <> 'ACCEPTED' OR NEW.revision <> 1 OR NEW.enrollment_upper_id IS NOT NULL OR NEW.enrollment_after_id <> 0 OR
           NEW.enrollment_complete OR NEW.completed_at IS NOT NULL OR NEW.delete_at IS NOT NULL THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_emergency_task_initial', MESSAGE = 'progress must begin unobserved and pending';
        END IF;
        RETURN NEW;
    END IF;
    IF OLD.state <> 'ACCEPTED' OR NEW.revision <> OLD.revision + 1 OR
       ROW(NEW.id, NEW.create_at, NEW.emergency_cancellation_id, NEW.strategy_instance_id, NEW.delete_at)
       IS DISTINCT FROM ROW(OLD.id, OLD.create_at, OLD.emergency_cancellation_id, OLD.strategy_instance_id, OLD.delete_at) OR
       (OLD.enrollment_upper_id IS NOT NULL AND NEW.enrollment_upper_id IS DISTINCT FROM OLD.enrollment_upper_id) OR
       NEW.enrollment_after_id < OLD.enrollment_after_id OR (OLD.enrollment_complete AND NOT NEW.enrollment_complete) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_emergency_task_history', MESSAGE = 'progress identity, cursor and final proof are immutable';
    END IF;
    SELECT * INTO budget FROM strategy_budgets WHERE strategy_instance_id = NEW.strategy_instance_id FOR SHARE;
    IF budget.id IS NULL OR budget.enabled OR budget.delete_at IS NOT NULL OR
       EXISTS (SELECT 1 FROM risk_snapshots WHERE strategy_instance_id = NEW.strategy_instance_id AND delete_at IS NULL AND allow_new_risk) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_emergency_task_risk', MESSAGE = 'enrollment requires actual closed new risk';
    END IF;
    IF OLD.enrollment_upper_id IS NULL AND NEW.enrollment_upper_id IS NOT NULL THEN
        SELECT COALESCE(max(id), 0) INTO actual_upper FROM order_intents WHERE strategy_instance_id = NEW.strategy_instance_id AND delete_at IS NULL;
        IF NEW.enrollment_upper_id <> actual_upper OR
           EXISTS (SELECT 1 FROM strategy_actions WHERE strategy_instance_id = NEW.strategy_instance_id AND kind = 'SUBMIT'
               AND state IN ('PENDING', 'DISPATCHING', 'WAITING', 'UNKNOWN') AND delete_at IS NULL) THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_emergency_task_enrollment', MESSAGE = 'enrollment requires a complete submission barrier';
        END IF;
    END IF;
    IF EXISTS (SELECT 1 FROM order_intents i WHERE i.strategy_instance_id = NEW.strategy_instance_id AND i.delete_at IS NULL
        AND i.id <= NEW.enrollment_after_id AND (i.state IN ('INTENT', 'SUBMITTING', 'LIVE', 'PARTIALLY_FILLED', 'UNKNOWN') OR i.reserved_quote_notional <> 0)
        AND NOT EXISTS (SELECT 1 FROM admin_order_cancellations c WHERE c.emergency_cancellation_id = scope_row.id AND c.order_intent_id = i.id)) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_emergency_task_enrollment', MESSAGE = 'enrollment cursor cannot skip obligations';
    END IF;
    IF NEW.state <> 'ACCEPTED' THEN
        SELECT count(*),
            count(*) FILTER (WHERE c.state <> 'ACCEPTED' AND i.state IN ('FILLED', 'CANCELED', 'REJECTED') AND i.reserved_quote_notional = 0
                AND NOT EXISTS (SELECT 1 FROM simulator_orders o WHERE o.strategy_instance_id = i.strategy_instance_id AND o.account_id = i.account_id
                    AND o.client_order_id = i.client_order_id AND o.state IN ('LIVE', 'PARTIALLY_FILLED') AND o.delete_at IS NULL)),
            count(*) FILTER (WHERE c.state = 'FAILED' AND i.state IN ('LIVE', 'PARTIALLY_FILLED'))
        INTO target_count, terminal_count, failed_count
        FROM admin_order_cancellations c JOIN order_intents i ON i.id = c.order_intent_id
        WHERE c.emergency_cancellation_id = scope_row.id;
        IF NOT NEW.enrollment_complete OR target_count <> terminal_count + failed_count OR
           EXISTS (SELECT 1 FROM strategy_actions WHERE strategy_instance_id = NEW.strategy_instance_id AND kind = 'SUBMIT'
               AND state IN ('PENDING', 'DISPATCHING', 'WAITING', 'UNKNOWN') AND delete_at IS NULL) OR
           EXISTS (SELECT 1 FROM order_intents i WHERE i.strategy_instance_id = NEW.strategy_instance_id AND i.delete_at IS NULL
               AND (i.state IN ('INTENT', 'SUBMITTING', 'LIVE', 'PARTIALLY_FILLED', 'UNKNOWN') OR i.reserved_quote_notional <> 0)
               AND NOT EXISTS (SELECT 1 FROM admin_order_cancellations c WHERE c.emergency_cancellation_id = scope_row.id AND c.order_intent_id = i.id)) OR
           EXISTS (SELECT 1 FROM simulator_orders o WHERE o.strategy_instance_id = NEW.strategy_instance_id AND o.state IN ('LIVE', 'PARTIALLY_FILLED') AND o.delete_at IS NULL
               AND NOT EXISTS (SELECT 1 FROM order_intents i JOIN admin_order_cancellations c ON c.order_intent_id = i.id
                   WHERE c.emergency_cancellation_id = scope_row.id AND i.account_id = o.account_id AND i.client_order_id = o.client_order_id)) OR
           (NEW.state = 'SUCCEEDED' AND (terminal_count <> target_count OR
               EXISTS (SELECT 1 FROM simulator_orders WHERE strategy_instance_id = NEW.strategy_instance_id AND state IN ('LIVE', 'PARTIALLY_FILLED') AND delete_at IS NULL))) OR
           (NEW.state = 'FAILED' AND failed_count = 0) THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_emergency_task_proof', MESSAGE = 'completion requires resolved scoped obligations';
        END IF;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER admin_emergency_task_guard BEFORE INSERT OR UPDATE OR DELETE ON admin_emergency_cancellation_tasks
    FOR EACH ROW EXECUTE FUNCTION guard_admin_emergency_task();

-- Backfill only an explicitly pending marker; no target, completion, permission
-- or funding is invented for existing accepted scopes.
INSERT INTO admin_emergency_cancellation_tasks(create_at, update_at, emergency_cancellation_id, strategy_instance_id, enrollment_after_id, enrollment_complete, state, revision)
    SELECT floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint, floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint,
        id, strategy_instance_id, 0, false, 'ACCEPTED', 1 FROM admin_emergency_cancellations;

CREATE FUNCTION initialize_admin_emergency_task() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE now_ms bigint;
BEGIN
    now_ms := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
    INSERT INTO admin_emergency_cancellation_tasks(create_at, update_at, emergency_cancellation_id, strategy_instance_id, enrollment_after_id, enrollment_complete, state, revision)
        VALUES (now_ms, now_ms, NEW.id, NEW.strategy_instance_id, 0, false, 'ACCEPTED', 1);
    RETURN NULL;
END;
$$;
CREATE TRIGGER admin_emergency_task_initialize AFTER INSERT ON admin_emergency_cancellations
    FOR EACH ROW EXECUTE FUNCTION initialize_admin_emergency_task();

CREATE OR REPLACE FUNCTION admin_emergency_scope_pending(scope_strategy_id bigint) RETURNS boolean
LANGUAGE sql STABLE AS $$
    SELECT EXISTS (SELECT 1 FROM admin_emergency_cancellations s
        LEFT JOIN admin_emergency_cancellation_tasks t ON t.emergency_cancellation_id = s.id
        WHERE s.strategy_instance_id = scope_strategy_id AND s.delete_at IS NULL AND (t.id IS NULL OR t.state = 'ACCEPTED'));
$$;

CREATE OR REPLACE FUNCTION guard_admin_order_cancellation() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    principal admin_users%ROWTYPE;
    session admin_sessions%ROWTYPE;
    strategy strategy_instances%ROWTYPE;
    intent order_intents%ROWTYPE;
    audit admin_audits%ROWTYPE;
    action strategy_actions%ROWTYPE;
    scope_row admin_emergency_cancellations%ROWTYPE;
    task_row admin_emergency_cancellation_tasks%ROWTYPE;
    scope_audit admin_audits%ROWTYPE;
    actor_name varchar(64);
    actor_role varchar(16);
    now_ms bigint;
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_cancellation_history', MESSAGE = 'cancellation history cannot be deleted';
    END IF;
    IF TG_OP = 'UPDATE' AND (
        OLD.state <> 'ACCEPTED' OR NEW.revision <> OLD.revision + 1 OR
        ROW(NEW.id, NEW.create_at, NEW.actor_user_id, NEW.actor_session_id, NEW.strategy_instance_id, NEW.order_intent_id,
            NEW.audit_id, NEW.idempotency_key, NEW.request_fingerprint, NEW.expected_order_revision, NEW.reason, NEW.emergency_cancellation_id, NEW.delete_at)
        IS DISTINCT FROM ROW(OLD.id, OLD.create_at, OLD.actor_user_id, OLD.actor_session_id, OLD.strategy_instance_id, OLD.order_intent_id,
            OLD.audit_id, OLD.idempotency_key, OLD.request_fingerprint, OLD.expected_order_revision, OLD.reason, OLD.emergency_cancellation_id, OLD.delete_at)
        OR (OLD.action_id IS NOT NULL AND NEW.action_id IS DISTINCT FROM OLD.action_id)
        OR (NEW.state = 'ACCEPTED' AND (OLD.action_id IS NOT NULL OR NEW.action_id IS NULL))) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_cancellation_history', MESSAGE = 'cancellation identity and final results are immutable';
    END IF;
    SELECT * INTO strategy FROM strategy_instances WHERE id = NEW.strategy_instance_id FOR SHARE;
    SELECT * INTO intent FROM order_intents WHERE id = NEW.order_intent_id FOR SHARE;
    IF strategy.id IS NULL OR intent.id IS NULL OR intent.strategy_instance_id <> strategy.id OR
       intent.account_id <> strategy.account_id OR intent.instrument_id <> strategy.instrument_id OR intent.delete_at IS NOT NULL THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_cancellation_scope', MESSAGE = 'cancellation requires its scoped order';
    END IF;
    IF TG_OP = 'INSERT' THEN
        IF NEW.emergency_cancellation_id IS NULL THEN
            SELECT * INTO principal FROM admin_users WHERE id = NEW.actor_user_id FOR SHARE;
            SELECT * INTO session FROM admin_sessions WHERE id = NEW.actor_session_id FOR SHARE;
            now_ms := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
            IF principal.id IS NULL OR session.id IS NULL OR NOT principal.enabled OR principal.delete_at IS NOT NULL OR
               principal.role NOT IN ('operator', 'admin') OR session.user_id <> principal.id OR session.delete_at IS NOT NULL OR
               session.revoked_at IS NOT NULL OR session.credential_version <> principal.credential_version OR session.expires_at <= now_ms THEN
                RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_cancellation_authority', MESSAGE = 'cancellation requires current authority';
            END IF;
            actor_name := principal.username;
            actor_role := principal.role;
        ELSE
            -- The already accepted scope delegates only bounded cancellation.
            -- No expired bearer is reused or re-authorized; actor/role come from
            -- its immutable acceptance audit, and dispatch still fences normally.
            SELECT * INTO scope_row FROM admin_emergency_cancellations WHERE id = NEW.emergency_cancellation_id;
            SELECT * INTO task_row FROM admin_emergency_cancellation_tasks WHERE emergency_cancellation_id = NEW.emergency_cancellation_id;
            SELECT * INTO scope_audit FROM admin_audits WHERE id = scope_row.audit_id;
            IF scope_row.id IS NULL OR scope_audit.id IS NULL OR task_row.id IS NULL OR task_row.state <> 'ACCEPTED' OR
               scope_row.strategy_instance_id <> strategy.id OR task_row.strategy_instance_id <> strategy.id OR
               scope_row.actor_user_id <> NEW.actor_user_id OR scope_row.actor_session_id <> NEW.actor_session_id OR
               scope_row.reason <> NEW.reason OR task_row.enrollment_upper_id IS NULL OR
               intent.id > task_row.enrollment_upper_id OR intent.id > task_row.enrollment_after_id OR
               NOT EXISTS (SELECT 1 FROM strategy_budgets WHERE strategy_instance_id = strategy.id AND account_id = strategy.account_id AND NOT enabled AND delete_at IS NULL) THEN
                RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_cancellation_emergency_scope', MESSAGE = 'cancellation requires its enrolled accepted scope';
            END IF;
            actor_name := scope_audit.actor;
            actor_role := scope_audit.actor_role;
        END IF;
        SELECT * INTO audit FROM admin_audits WHERE id = NEW.audit_id;
        IF strategy.delete_at IS NOT NULL OR intent.revision <> NEW.expected_order_revision OR NEW.revision <> 1 OR
           NEW.state <> 'ACCEPTED' OR NEW.action_id IS NOT NULL OR audit.id IS NULL OR audit.actor <> actor_name OR
           audit.actor_role <> actor_role OR audit.action <> 'order.cancel' OR audit.resource <> 'strategy_order:' || intent.id::text OR
           audit.reason <> NEW.reason OR audit.before_version IS DISTINCT FROM NEW.expected_order_revision OR
           audit.after_version IS DISTINCT FROM NEW.expected_order_revision THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_cancellation_acceptance', MESSAGE = 'cancellation requires its confirmed order and audit';
        END IF;
    END IF;
    IF NEW.action_id IS NOT NULL THEN
        SELECT * INTO action FROM strategy_actions WHERE id = NEW.action_id FOR SHARE;
        IF action.id IS NULL OR action.kind <> 'CANCEL' OR action.strategy_instance_id <> strategy.id OR action.intent_id <> intent.id OR
           action.account_id <> intent.account_id OR action.instrument_id <> intent.instrument_id OR action.client_order_id <> intent.client_order_id THEN
            RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_cancellation_action', MESSAGE = 'cancellation requires a matching action';
        END IF;
    END IF;
    IF NEW.state <> 'ACCEPTED' AND (intent.revision <> NEW.observed_order_revision OR intent.state <> NEW.observed_order_state) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_cancellation_observation', MESSAGE = 'cancellation requires current OMS proof';
    END IF;
    IF NEW.state = 'SUCCEEDED' AND (intent.state NOT IN ('FILLED', 'CANCELED', 'REJECTED') OR intent.reserved_quote_notional <> 0 OR
       EXISTS (SELECT 1 FROM simulator_orders WHERE strategy_instance_id = strategy.id AND account_id = intent.account_id
           AND client_order_id = intent.client_order_id AND state IN ('LIVE', 'PARTIALLY_FILLED') AND delete_at IS NULL)) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_cancellation_observation', MESSAGE = 'cancellation requires terminal obligations';
    END IF;
    IF NEW.state = 'FAILED' AND NOT (
        (NEW.outcome_code = 'cancel_not_accepted' AND action.state = 'NOT_ACCEPTED') OR
        (NEW.outcome_code = 'cancel_rejected' AND action.state = 'OBSERVED' AND action.observed_cancellation_state = 'REJECTED')) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_cancellation_observation', MESSAGE = 'cancellation failure requires original action proof';
    END IF;
    RETURN NEW;
END;
$$;

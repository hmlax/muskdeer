CREATE TABLE admin_strategy_creations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL CHECK (delete_at IS NULL),
    actor_user_id bigint NOT NULL REFERENCES admin_users(id),
    actor_session_id bigint NOT NULL REFERENCES admin_sessions(id),
    strategy_instance_id bigint NOT NULL CONSTRAINT uk_admin_strategy_creation_instance UNIQUE REFERENCES strategy_instances(id),
    audit_id bigint NOT NULL CONSTRAINT uk_admin_strategy_creation_audit UNIQUE REFERENCES admin_audits(id),
    idempotency_key varchar(64) NOT NULL CHECK (idempotency_key ~ '^[A-Za-z0-9_.:-]{16,64}$'),
    request_fingerprint char(64) NOT NULL CHECK (request_fingerprint ~ '^[0-9a-f]{64}$'),
    config_version bigint NOT NULL CHECK (config_version = 1),
    revision bigint NOT NULL CHECK (revision = 1),
    market_data_source varchar(32) NOT NULL CHECK (market_data_source IN ('binance', 'okx')),
    reason varchar(256) NOT NULL CHECK (length(reason) > 0),
    CONSTRAINT uk_admin_strategy_creation_key UNIQUE (actor_user_id, idempotency_key)
);

CREATE FUNCTION guard_admin_strategy_creation() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    principal admin_users%ROWTYPE;
    session admin_sessions%ROWTYPE;
    audit admin_audits%ROWTYPE;
    strategy strategy_instances%ROWTYPE;
    config strategy_config_versions%ROWTYPE;
    budget strategy_budgets%ROWTYPE;
    expected_limit numeric;
BEGIN
    IF TG_OP <> 'INSERT' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_creation_history', MESSAGE = 'creation history is immutable';
    END IF;
    SELECT * INTO principal FROM admin_users WHERE id = NEW.actor_user_id FOR SHARE;
    SELECT * INTO session FROM admin_sessions WHERE id = NEW.actor_session_id FOR SHARE;
    SELECT * INTO strategy FROM strategy_instances WHERE id = NEW.strategy_instance_id FOR SHARE;
    IF principal.id IS NULL OR session.id IS NULL OR NOT principal.enabled OR principal.delete_at IS NOT NULL OR
       principal.role NOT IN ('operator', 'admin') OR session.user_id <> principal.id OR session.delete_at IS NOT NULL OR
       session.revoked_at IS NOT NULL OR session.credential_version <> principal.credential_version OR
       session.expires_at <= floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_creation_authority', MESSAGE = 'creation requires current operator authority';
    END IF;
    SELECT * INTO audit FROM admin_audits WHERE id = NEW.audit_id;
    SELECT * INTO config FROM strategy_config_versions WHERE instance_id = NEW.strategy_instance_id AND version = 1;
    SELECT * INTO budget FROM strategy_budgets WHERE strategy_instance_id = NEW.strategy_instance_id;
    IF audit.id IS NULL OR audit.delete_at IS NOT NULL OR audit.actor <> principal.username OR audit.actor_role <> principal.role OR
       audit.action <> 'strategy.create' OR audit.resource <> 'strategy_instance:' || NEW.strategy_instance_id::text OR
       audit.reason <> NEW.reason OR audit.before_version IS NOT NULL OR audit.after_version IS DISTINCT FROM 1::bigint THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_creation_audit', MESSAGE = 'creation requires matching immutable audit';
    END IF;
    IF strategy.id IS NULL OR strategy.delete_at IS NOT NULL OR strategy.revision <> 1 OR strategy.state <> 'CREATED' OR
       strategy.desired_state <> 'STOPPED' OR strategy.desired_running OR strategy.requested_config_version <> 1 OR
       strategy.active_config_version IS NOT NULL OR strategy.active_market_data_source IS NOT NULL OR strategy.runtime_owner_epoch <> 0 OR
       strategy.market_data_source <> NEW.market_data_source OR config.id IS NULL OR config.delete_at IS NOT NULL OR
       config.parameters_schema_version <> 1 OR config.template <> strategy.template OR config.code_version <> strategy.code_version OR
       config.market_data_source <> NEW.market_data_source OR config.created_by <> principal.username OR
       budget.id IS NULL OR budget.delete_at IS NOT NULL OR budget.account_id <> strategy.account_id OR
       NOT budget.enabled OR budget.reserved_notional <> 0 OR budget.revision <> 1 THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_creation_effect', MESSAGE = 'creation requires initial stopped metadata and budget';
    END IF;
    expected_limit := CASE strategy.template
        WHEN 'market_maker' THEN (config.maker_parameters->>'side_budget')::numeric * 2
        WHEN 'grid' THEN (config.grid_parameters->>'total_budget')::numeric END;
    IF expected_limit IS NULL OR budget.limit_notional <> expected_limit THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_creation_effect', MESSAGE = 'creation budget must match typed parameters';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER admin_strategy_creation BEFORE INSERT OR UPDATE OR DELETE ON admin_strategy_creations
    FOR EACH ROW EXECUTE FUNCTION guard_admin_strategy_creation();

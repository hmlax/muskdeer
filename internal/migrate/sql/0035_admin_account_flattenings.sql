-- Immutable confirmation is not execution authority or completion. Durable
-- work and account-wide mutual-exclusion barriers follow in later versions.
CREATE TABLE admin_account_flattenings (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL CHECK (delete_at IS NULL),
    actor_user_id bigint NOT NULL REFERENCES admin_users(id),
    actor_session_id bigint NOT NULL REFERENCES admin_sessions(id),
    strategy_instance_id bigint NOT NULL REFERENCES strategy_instances(id),
    account_id varchar(64) NOT NULL REFERENCES simulator_accounts(account_id),
    instrument_id bigint NOT NULL REFERENCES instruments(id),
    emergency_cancellation_id bigint NOT NULL REFERENCES admin_emergency_cancellations(id),
    audit_id bigint NOT NULL CONSTRAINT uk_admin_account_flattening_audit UNIQUE REFERENCES admin_audits(id),
    idempotency_key varchar(64) NOT NULL CHECK (idempotency_key ~ '^[A-Za-z0-9_.:-]{16,64}$'),
    request_fingerprint char(64) NOT NULL CHECK (request_fingerprint ~ '^[0-9a-f]{64}$'),
    scope varchar(32) NOT NULL CHECK (scope = 'account_instrument'),
    expected_risk_revision bigint NOT NULL CHECK (expected_risk_revision > 0),
    expected_portfolio_revision bigint NOT NULL CHECK (expected_portfolio_revision > 0),
    expected_base_revision bigint NOT NULL CHECK (expected_base_revision > 0),
    confirmed_quantity numeric(76,36) NOT NULL CHECK (confirmed_quantity >= 0 AND confirmed_quantity <> 'NaN'::numeric),
    limit_price numeric(38,18) NOT NULL CHECK (limit_price > 0 AND limit_price <> 'NaN'::numeric),
    reason varchar(256) NOT NULL CHECK (length(reason) > 0 AND octet_length(reason) <= 256),
    CONSTRAINT uk_admin_account_flattening_key UNIQUE (actor_user_id, idempotency_key)
);
CREATE INDEX idx_admin_account_flattening_strategy ON admin_account_flattenings(strategy_instance_id, id);
CREATE INDEX idx_admin_account_flattening_account ON admin_account_flattenings(account_id, id);

CREATE FUNCTION keep_admin_account_flattening_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_flatten_history', MESSAGE = 'flatten confirmation history is immutable';
END;
$$;
CREATE TRIGGER admin_account_flattening_history BEFORE UPDATE OR DELETE ON admin_account_flattenings
    FOR EACH ROW EXECUTE FUNCTION keep_admin_account_flattening_history();

CREATE FUNCTION guard_admin_account_flattening() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    principal admin_users%ROWTYPE;
    session admin_sessions%ROWTYPE;
    strategy strategy_instances%ROWTYPE;
    instrument instruments%ROWTYPE;
    account simulator_accounts%ROWTYPE;
    account_budget account_budgets%ROWTYPE;
    budget strategy_budgets%ROWTYPE;
    base_balance simulator_balances%ROWTYPE;
    quote_balance simulator_balances%ROWTYPE;
    portfolio portfolio_accounts%ROWTYPE;
    cancellation admin_emergency_cancellations%ROWTYPE;
    task admin_emergency_cancellation_tasks%ROWTYPE;
    audit admin_audits%ROWTYPE;
    risk_revision bigint;
    source_count bigint;
    source_latest bigint;
    now_ms bigint;
BEGIN
    SELECT * INTO principal FROM admin_users WHERE id = NEW.actor_user_id FOR SHARE;
    SELECT * INTO session FROM admin_sessions WHERE id = NEW.actor_session_id FOR SHARE;
    now_ms := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
    IF principal.id IS NULL OR session.id IS NULL OR NOT principal.enabled OR principal.delete_at IS NOT NULL OR principal.role <> 'admin' OR
       session.user_id <> principal.id OR session.delete_at IS NOT NULL OR session.revoked_at IS NOT NULL OR
       session.credential_version <> principal.credential_version OR session.expires_at <= now_ms THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_flatten_authority', MESSAGE = 'flatten confirmation requires current administrator authority';
    END IF;
    SELECT * INTO strategy FROM strategy_instances WHERE id = NEW.strategy_instance_id FOR SHARE;
    SELECT * INTO instrument FROM instruments WHERE id = NEW.instrument_id FOR SHARE;
    SELECT * INTO account FROM simulator_accounts WHERE account_id = NEW.account_id FOR SHARE;
    SELECT * INTO account_budget FROM account_budgets WHERE account_id = NEW.account_id FOR SHARE;
    SELECT * INTO budget FROM strategy_budgets WHERE strategy_instance_id = NEW.strategy_instance_id FOR SHARE;
    IF strategy.id IS NULL OR strategy.delete_at IS NOT NULL OR strategy.account_id <> NEW.account_id OR strategy.instrument_id <> NEW.instrument_id OR
       instrument.id IS NULL OR instrument.delete_at IS NOT NULL OR instrument.execution_venue <> 'simulator' OR instrument.status <> 'TRADING' OR
       account.id IS NULL OR account.delete_at IS NOT NULL OR NOT account.enabled OR
       account_budget.id IS NULL OR account_budget.delete_at IS NOT NULL OR account_budget.asset <> instrument.quote_asset OR
       budget.id IS NULL OR budget.delete_at IS NOT NULL OR budget.account_id <> NEW.account_id OR budget.enabled OR
       (SELECT count(*) FROM strategy_instances WHERE account_id = NEW.account_id AND delete_at IS NULL) <> 1 THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_flatten_scope', MESSAGE = 'flatten confirmation requires one isolated simulated strategy account';
    END IF;
    SELECT * INTO cancellation FROM admin_emergency_cancellations WHERE id = NEW.emergency_cancellation_id;
    SELECT * INTO task FROM admin_emergency_cancellation_tasks WHERE emergency_cancellation_id = NEW.emergency_cancellation_id FOR SHARE;
    SELECT COALESCE(max(revision), 1) INTO risk_revision FROM admin_strategy_risk_changes WHERE strategy_instance_id = strategy.id;
    IF cancellation.id IS NULL OR cancellation.strategy_instance_id <> strategy.id OR cancellation.scope <> 'strategy' OR
       cancellation.risk_revision <> NEW.expected_risk_revision OR risk_revision <> NEW.expected_risk_revision OR
       task.id IS NULL OR task.state <> 'SUCCEEDED' OR NOT task.enrollment_complete OR task.completed_at IS NULL OR task.completed_at > now_ms OR
       EXISTS (SELECT 1 FROM risk_snapshots WHERE account_id = NEW.account_id AND delete_at IS NULL AND allow_new_risk) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_flatten_confirmation', MESSAGE = 'flatten confirmation requires its current completed cancellation and closed risk';
    END IF;
    -- Match the existing core lock order; both balances are locked by asset.
    PERFORM id FROM simulator_balances WHERE account_id = NEW.account_id AND asset IN (instrument.base_asset, instrument.quote_asset) ORDER BY asset FOR SHARE;
    SELECT * INTO base_balance FROM simulator_balances WHERE account_id = NEW.account_id AND asset = instrument.base_asset;
    SELECT * INTO quote_balance FROM simulator_balances WHERE account_id = NEW.account_id AND asset = instrument.quote_asset;
    SELECT * INTO portfolio FROM portfolio_accounts WHERE account_id = NEW.account_id FOR SHARE;
    SELECT count(*), COALESCE(max(f.id), 0) INTO source_count, source_latest FROM simulator_fills f
        JOIN simulator_orders o ON o.id = f.core_order_id WHERE o.account_id = NEW.account_id AND o.instrument_id = NEW.instrument_id;
    IF base_balance.id IS NULL OR quote_balance.id IS NULL OR base_balance.delete_at IS NOT NULL OR quote_balance.delete_at IS NOT NULL OR
       portfolio.id IS NULL OR portfolio.delete_at IS NOT NULL OR portfolio.instrument_id <> NEW.instrument_id OR
       portfolio.base_asset <> instrument.base_asset OR portfolio.quote_asset <> instrument.quote_asset OR NOT portfolio.reconciled OR
       base_balance.revision <> NEW.expected_base_revision OR portfolio.revision <> NEW.expected_portfolio_revision OR
       base_balance.frozen <> 0 OR quote_balance.frozen <> 0 OR base_balance.available <> NEW.confirmed_quantity OR portfolio.quantity <> NEW.confirmed_quantity OR
       portfolio.cash_quote <> quote_balance.available OR source_count > 10000 OR source_latest <> portfolio.last_source_sequence OR
       source_count <> (SELECT count(*) FROM portfolio_fills WHERE account_id = NEW.account_id AND instrument_id = NEW.instrument_id AND delete_at IS NULL) OR
       account_budget.reserved_notional <> 0 OR budget.reserved_notional <> 0 OR
       EXISTS (SELECT 1 FROM order_intents WHERE account_id = NEW.account_id AND delete_at IS NULL AND
           (state IN ('INTENT', 'SUBMITTING', 'LIVE', 'PARTIALLY_FILLED', 'UNKNOWN') OR reserved_quote_notional <> 0)) OR
       EXISTS (SELECT 1 FROM simulator_orders WHERE account_id = NEW.account_id AND delete_at IS NULL AND state IN ('LIVE', 'PARTIALLY_FILLED')) OR
       EXISTS (SELECT 1 FROM strategy_actions WHERE account_id = NEW.account_id AND delete_at IS NULL AND state IN ('PENDING', 'DISPATCHING', 'WAITING', 'UNKNOWN')) OR
       EXISTS (SELECT 1 FROM cancellation_requests WHERE account_id = NEW.account_id AND delete_at IS NULL AND state IN ('REQUESTED', 'SUBMITTING', 'PENDING', 'UNKNOWN')) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_flatten_confirmation', MESSAGE = 'flatten confirmation requires current reconciled balances and resolved obligations';
    END IF;
    IF mod(NEW.limit_price, instrument.price_tick) <> 0 OR (NEW.confirmed_quantity > 0 AND (
       NEW.confirmed_quantity >= 100000000000000000000 OR NEW.confirmed_quantity <> trunc(NEW.confirmed_quantity, 18) OR
       mod(NEW.confirmed_quantity, instrument.quantity_step) <> 0 OR NEW.confirmed_quantity * NEW.limit_price < instrument.min_notional OR
       NEW.confirmed_quantity * NEW.limit_price > LEAST(account_budget.limit_notional, budget.limit_notional))) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_flatten_confirmation', MESSAGE = 'flatten confirmation must retain exact orderable quantity and price';
    END IF;
    SELECT * INTO audit FROM admin_audits WHERE id = NEW.audit_id;
    IF audit.id IS NULL OR audit.delete_at IS NOT NULL OR audit.actor <> principal.username OR audit.actor_role <> principal.role OR
       audit.action <> 'account.flatten' OR audit.resource <> 'account_instrument:' || NEW.account_id || ':' || NEW.instrument_id::text OR
       audit.reason <> NEW.reason OR audit.before_version IS DISTINCT FROM NEW.expected_portfolio_revision OR audit.after_version IS DISTINCT FROM NEW.expected_portfolio_revision THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_flatten_audit', MESSAGE = 'flatten confirmation requires its separate scoped audit';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER admin_account_flattening_commit AFTER INSERT ON admin_account_flattenings
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION guard_admin_account_flattening();

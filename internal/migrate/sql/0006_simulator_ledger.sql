ALTER TABLE simulator_orders ADD COLUMN quote_fee_rate numeric(18,18) NOT NULL DEFAULT 0
    CHECK (quote_fee_rate >= 0 AND quote_fee_rate < 1 AND quote_fee_rate <> 'NaN'::numeric);
CREATE TABLE simulator_accounts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    account_id varchar(64) NOT NULL CHECK (length(account_id) > 0),
    subject_id varchar(64) NOT NULL CHECK (length(subject_id) > 0),
    enabled boolean NOT NULL,
    quote_fee_rate numeric(18,18) NOT NULL CHECK (quote_fee_rate >= 0 AND quote_fee_rate < 1 AND quote_fee_rate <> 'NaN'::numeric),
    revision bigint NOT NULL CHECK (revision > 0),
    CONSTRAINT uk_simulator_account_key UNIQUE (account_id)
);
CREATE INDEX idx_simulator_account_subject ON simulator_accounts(subject_id);
CREATE TABLE simulator_balances (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    account_id varchar(64) NOT NULL REFERENCES simulator_accounts(account_id),
    asset varchar(32) NOT NULL CHECK (length(asset) > 0),
    available numeric(76,36) NOT NULL CHECK (available >= 0 AND available <> 'NaN'::numeric),
    frozen numeric(76,36) NOT NULL CHECK (frozen >= 0 AND frozen <> 'NaN'::numeric),
    revision bigint NOT NULL CHECK (revision > 0),
    CONSTRAINT uk_simulator_balance_account_asset UNIQUE (account_id, asset)
);
CREATE TABLE simulator_fills (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    trade_id varchar(128) NOT NULL CHECK (length(trade_id) > 0),
    core_order_id bigint NOT NULL REFERENCES simulator_orders(id),
    price numeric(38,18) NOT NULL CHECK (price > 0 AND price <> 'NaN'::numeric),
    quantity numeric(38,18) NOT NULL CHECK (quantity > 0 AND quantity <> 'NaN'::numeric),
    quote_notional numeric(76,36) NOT NULL CHECK (quote_notional = price * quantity AND quote_notional <> 'NaN'::numeric),
    fee_amount numeric(76,36) NOT NULL CHECK (fee_amount >= 0 AND fee_amount < quote_notional AND fee_amount <> 'NaN'::numeric),
    fee_asset varchar(32) NOT NULL CHECK (length(fee_asset) > 0),
    counterparty_subject varchar(64) NOT NULL CHECK (length(counterparty_subject) > 0),
    CONSTRAINT uk_simulator_fill_trade UNIQUE (trade_id)
);
CREATE INDEX idx_simulator_fill_order ON simulator_fills(core_order_id);
CREATE TRIGGER simulator_fill_immutable BEFORE UPDATE OR DELETE ON simulator_fills
    FOR EACH ROW EXECUTE FUNCTION reject_simulator_command_change();

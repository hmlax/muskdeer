CREATE TABLE IF NOT EXISTS schema_migrations (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    version bigint NOT NULL,
    name varchar(128) NOT NULL,
    checksum varchar(64) NOT NULL,
    CONSTRAINT uk_schema_migration_version UNIQUE (version),
    CONSTRAINT ck_schema_migration_version CHECK (version > 0),
    CONSTRAINT ck_schema_migration_name CHECK (length(name) > 0),
    CONSTRAINT ck_schema_migration_checksum CHECK (checksum ~ '^[0-9a-f]{64}$')
);

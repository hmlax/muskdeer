-- Numeric comparisons alone do not exclude PostgreSQL's numeric NaN.
ALTER TABLE instruments ADD CONSTRAINT ck_instrument_finite CHECK (
    price_tick <> 'NaN'::numeric AND quantity_step <> 'NaN'::numeric AND min_notional <> 'NaN'::numeric
);

CREATE TABLE simulator_commands (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    account_id varchar(64) NOT NULL CHECK (length(account_id) > 0),
    command_key varchar(128) NOT NULL CHECK (length(command_key) > 0),
    action varchar(16) NOT NULL CHECK (action IN ('SUBMIT', 'CANCEL')),
    client_order_id varchar(64) NOT NULL CHECK (length(client_order_id) > 0),
    strategy_instance_id bigint NOT NULL REFERENCES strategy_instances(id),
    config_version bigint NOT NULL,
    owner_id varchar(128) NOT NULL CHECK (length(owner_id) > 0),
    owner_epoch bigint NOT NULL CHECK (owner_epoch > 0),
    execution_owner_id varchar(128) NOT NULL CHECK (length(execution_owner_id) > 0),
    execution_epoch bigint NOT NULL CHECK (execution_epoch > 0),
    instrument_id bigint NOT NULL REFERENCES instruments(id),
    fingerprint char(64) NOT NULL CHECK (fingerprint ~ '^[0-9a-f]{64}$'),
    deadline_at bigint NOT NULL CHECK (deadline_at > 0),
    CONSTRAINT uk_simulator_command_account_key UNIQUE (account_id, command_key),
    CONSTRAINT uk_simulator_command_target UNIQUE (id, account_id, client_order_id),
    CONSTRAINT uk_simulator_command_identity UNIQUE (id, account_id, client_order_id, strategy_instance_id, config_version, instrument_id),
    CONSTRAINT fk_simulator_command_config FOREIGN KEY (strategy_instance_id, config_version) REFERENCES strategy_config_versions(instance_id, version)
);

CREATE TABLE simulator_orders (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    account_id varchar(64) NOT NULL,
    client_order_id varchar(64) NOT NULL,
    initial_command_id bigint NOT NULL,
    strategy_instance_id bigint NOT NULL,
    config_version bigint NOT NULL,
    instrument_id bigint NOT NULL,
    side varchar(8) NOT NULL CHECK (side IN ('BUY', 'SELL')),
    price numeric(38,18) NOT NULL CHECK (price > 0 AND price <> 'NaN'::numeric),
    quantity numeric(38,18) NOT NULL CHECK (quantity > 0 AND quantity <> 'NaN'::numeric),
    filled_quantity numeric(38,18) NOT NULL CHECK (filled_quantity >= 0 AND filled_quantity <= quantity AND filled_quantity <> 'NaN'::numeric),
    time_in_force varchar(16) NOT NULL CHECK (time_in_force IN ('GTC', 'IOC', 'POST_ONLY')),
    reduce_only boolean NOT NULL,
    state varchar(32) NOT NULL CHECK (state IN ('LIVE', 'PARTIALLY_FILLED', 'FILLED', 'CANCELED', 'REJECTED')),
    cancel_state varchar(16) NOT NULL CHECK (cancel_state IN ('NONE', 'REQUESTED', 'PENDING', 'CONFIRMED', 'UNKNOWN', 'REJECTED')),
    frozen_asset varchar(32) NOT NULL CHECK (length(frozen_asset) > 0),
    frozen_amount numeric(76,36) NOT NULL CHECK (frozen_amount >= 0 AND frozen_amount <> 'NaN'::numeric),
    revision bigint NOT NULL CHECK (revision > 0),
    last_command_id bigint NOT NULL,
    CONSTRAINT ck_simulator_order_fill_state CHECK (
        (state = 'LIVE' AND filled_quantity = 0)
        OR (state = 'PARTIALLY_FILLED' AND filled_quantity > 0 AND filled_quantity < quantity)
        OR (state = 'FILLED' AND filled_quantity = quantity)
        OR (state = 'CANCELED' AND filled_quantity < quantity)
        OR (state = 'REJECTED' AND filled_quantity = 0)
    ),
    CONSTRAINT ck_simulator_terminal_funds CHECK (state NOT IN ('FILLED', 'CANCELED', 'REJECTED') OR frozen_amount = 0),
    CONSTRAINT uk_simulator_order_account_client UNIQUE (account_id, client_order_id),
    CONSTRAINT uk_simulator_order_initial_command UNIQUE (initial_command_id),
    CONSTRAINT fk_simulator_order_last_command FOREIGN KEY (last_command_id, account_id, client_order_id) REFERENCES simulator_commands(id, account_id, client_order_id),
    CONSTRAINT fk_simulator_order_command FOREIGN KEY (initial_command_id, account_id, client_order_id, strategy_instance_id, config_version, instrument_id)
        REFERENCES simulator_commands(id, account_id, client_order_id, strategy_instance_id, config_version, instrument_id)
);
CREATE INDEX idx_simulator_order_strategy ON simulator_orders(strategy_instance_id);
CREATE INDEX idx_simulator_order_instrument ON simulator_orders(instrument_id);

-- This target-side check runs on command commit, with the order/funds effects
-- in the same transaction. Locks serialize it with takeover/config changes.
CREATE FUNCTION validate_simulator_command() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    strategy strategy_instances%ROWTYPE;
    strategy_lease strategy_leases%ROWTYPE;
    execution_lease execution_shard_leases%ROWTYPE;
    now_ms bigint;
BEGIN
    SELECT * INTO strategy FROM strategy_instances WHERE id = NEW.strategy_instance_id FOR SHARE;
    SELECT * INTO strategy_lease FROM strategy_leases WHERE strategy_instance_id = NEW.strategy_instance_id FOR UPDATE;
    SELECT * INTO execution_lease FROM execution_shard_leases WHERE account_id = NEW.account_id FOR UPDATE;
    now_ms := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
    IF strategy.id IS NULL OR strategy.delete_at IS NOT NULL OR strategy.account_id <> NEW.account_id
        OR strategy.instrument_id <> NEW.instrument_id OR strategy.active_config_version IS DISTINCT FROM NEW.config_version
        OR strategy_lease.id IS NULL OR strategy_lease.delete_at IS NOT NULL
        OR strategy_lease.owner_id <> NEW.owner_id OR strategy_lease.epoch <> NEW.owner_epoch OR strategy_lease.expires_at <= now_ms
        OR execution_lease.id IS NULL OR execution_lease.delete_at IS NOT NULL
        OR execution_lease.owner_id <> NEW.execution_owner_id OR execution_lease.epoch <> NEW.execution_epoch OR execution_lease.expires_at <= now_ms
        OR NEW.delete_at IS NOT NULL OR NEW.deadline_at <= now_ms THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'simulator command authority rejected', CONSTRAINT = 'simulator_command_fence';
    END IF;
    IF NEW.action = 'SUBMIT' AND (strategy.state <> 'RUNNING' OR NOT strategy.desired_running) THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'simulator new risk is disabled', CONSTRAINT = 'simulator_command_fence';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM strategy_config_versions WHERE instance_id = NEW.strategy_instance_id
        AND version = NEW.config_version AND delete_at IS NULL AND parameters_schema_version = 1) THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'simulator configuration rejected', CONSTRAINT = 'simulator_command_fence';
    END IF;
    IF (NEW.action = 'SUBMIT' AND NOT EXISTS (SELECT 1 FROM simulator_orders WHERE initial_command_id = NEW.id AND delete_at IS NULL))
        OR (NEW.action = 'CANCEL' AND NOT EXISTS (SELECT 1 FROM simulator_orders WHERE last_command_id = NEW.id AND cancel_state IN ('PENDING', 'CONFIRMED') AND delete_at IS NULL)) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'simulator command effect missing';
    END IF;
    RETURN NEW;
END;
$$;
CREATE CONSTRAINT TRIGGER simulator_command_fence AFTER INSERT ON simulator_commands
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_simulator_command();

CREATE FUNCTION reject_simulator_command_change() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'simulator commands are immutable';
END;
$$;
CREATE TRIGGER simulator_command_immutable BEFORE UPDATE OR DELETE ON simulator_commands
    FOR EACH ROW EXECUTE FUNCTION reject_simulator_command_change();

CREATE FUNCTION validate_simulator_order_origin() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM simulator_commands WHERE id = NEW.initial_command_id AND action = 'SUBMIT' AND delete_at IS NULL) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'simulator order origin rejected';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER simulator_order_origin BEFORE INSERT ON simulator_orders FOR EACH ROW EXECUTE FUNCTION validate_simulator_order_origin();

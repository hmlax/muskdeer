CREATE TABLE instruments (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    execution_venue varchar(32) NOT NULL CHECK (length(execution_venue) > 0),
    symbol varchar(64) NOT NULL CHECK (length(symbol) > 0),
    base_asset varchar(32) NOT NULL CHECK (length(base_asset) > 0),
    quote_asset varchar(32) NOT NULL CHECK (length(quote_asset) > 0 AND quote_asset <> base_asset),
    price_tick numeric(38,18) NOT NULL CHECK (price_tick > 0),
    quantity_step numeric(38,18) NOT NULL CHECK (quantity_step > 0),
    min_notional numeric(38,18) NOT NULL CHECK (min_notional > 0),
    status varchar(16) NOT NULL CHECK (status IN ('TRADING', 'HALTED')),
    metadata_version bigint NOT NULL CHECK (metadata_version > 0),
    CONSTRAINT uk_instrument_venue_symbol UNIQUE (execution_venue, symbol)
);

CREATE TABLE strategy_instances (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    instance_key varchar(64) NOT NULL CHECK (length(instance_key) > 0),
    template varchar(32) NOT NULL CHECK (template IN ('market_maker', 'grid')),
    account_id varchar(64) NOT NULL CHECK (length(account_id) > 0),
    instrument_id bigint NOT NULL REFERENCES instruments(id),
    code_version varchar(64) NOT NULL CHECK (length(code_version) > 0),
    revision bigint NOT NULL CHECK (revision > 0),
    state varchar(32) NOT NULL CHECK (state IN ('CREATED', 'STARTING', 'RECOVERING', 'RUNNING', 'PAUSING', 'PAUSED', 'STOPPING', 'STOPPED', 'ERROR')),
    desired_running boolean NOT NULL,
    requested_config_version bigint NOT NULL CHECK (requested_config_version > 0),
    market_data_source varchar(32) NOT NULL CHECK (market_data_source IN ('binance', 'okx')),
    active_config_version bigint NULL,
    active_market_data_source varchar(32) NULL,
    CONSTRAINT uk_strategy_instance_key UNIQUE (instance_key),
    CONSTRAINT ck_strategy_active_pair CHECK ((active_config_version IS NULL) = (active_market_data_source IS NULL)),
    CONSTRAINT ck_strategy_active_version CHECK (active_config_version IS NULL OR (active_config_version > 0 AND active_config_version <= requested_config_version)),
    CONSTRAINT ck_strategy_active_source CHECK (active_market_data_source IS NULL OR active_market_data_source IN ('binance', 'okx'))
);
CREATE INDEX idx_strategy_instance_account ON strategy_instances (account_id);
CREATE INDEX idx_strategy_instance_instrument ON strategy_instances (instrument_id);

CREATE TABLE strategy_config_versions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    instance_id bigint NOT NULL REFERENCES strategy_instances(id),
    version bigint NOT NULL CHECK (version > 0),
    market_data_source varchar(32) NOT NULL CHECK (market_data_source IN ('binance', 'okx')),
    code_version varchar(64) NOT NULL CHECK (length(code_version) > 0),
    created_by varchar(64) NOT NULL CHECK (length(created_by) > 0),
    CONSTRAINT uk_strategy_config_instance_version UNIQUE (instance_id, version),
    CONSTRAINT uk_strategy_config_source_version UNIQUE (instance_id, version, market_data_source)
);

ALTER TABLE strategy_instances ADD CONSTRAINT fk_strategy_requested_config
    FOREIGN KEY (id, requested_config_version, market_data_source)
    REFERENCES strategy_config_versions(instance_id, version, market_data_source)
    DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE strategy_instances ADD CONSTRAINT fk_strategy_active_config
    FOREIGN KEY (id, active_config_version, active_market_data_source)
    REFERENCES strategy_config_versions(instance_id, version, market_data_source)
    DEFERRABLE INITIALLY DEFERRED;

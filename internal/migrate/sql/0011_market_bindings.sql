CREATE TABLE market_feeds (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    source varchar(32) NOT NULL CHECK (source IN ('binance', 'okx')),
    instrument_id bigint NOT NULL REFERENCES instruments(id),
    external_symbol varchar(64) NOT NULL CHECK (length(external_symbol) BETWEEN 1 AND 64),
    mode varchar(16) NOT NULL CHECK (mode IN ('LIVE', 'REPLAY')),
    source_version bigint NOT NULL CHECK (source_version = 1),
    policy jsonb NOT NULL CHECK (jsonb_typeof(policy) = 'object'),
    CONSTRAINT uk_market_feed_scope UNIQUE (source, instrument_id, mode),
    CONSTRAINT ck_market_feed_symbol CHECK (
        (source = 'binance' AND external_symbol ~ '^[A-Z0-9]+$') OR
        (source = 'okx' AND external_symbol ~ '^[A-Z0-9-]+$')
    )
);
CREATE FUNCTION check_market_feed_product() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    product instruments%ROWTYPE;
    expected_symbol text;
BEGIN
    SELECT * INTO product FROM instruments WHERE id = NEW.instrument_id AND delete_at IS NULL FOR SHARE;
    IF NOT FOUND THEN
        RAISE EXCEPTION USING ERRCODE = '23503', MESSAGE = 'market feed instrument is unavailable';
    END IF;
    IF NEW.source = 'okx' THEN
        expected_symbol := product.base_asset || '-' || product.quote_asset;
    ELSE
        expected_symbol := product.base_asset || product.quote_asset;
    END IF;
    IF NEW.external_symbol <> expected_symbol THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'market feed product does not match underlying assets';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER market_feed_product BEFORE INSERT ON market_feeds
    FOR EACH ROW EXECUTE FUNCTION check_market_feed_product();

CREATE FUNCTION keep_bound_market_assets() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF ROW(NEW.base_asset, NEW.quote_asset) IS DISTINCT FROM ROW(OLD.base_asset, OLD.quote_asset)
        AND EXISTS (SELECT 1 FROM market_feeds WHERE instrument_id = OLD.id) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'bound market instrument assets are immutable';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER bound_market_assets BEFORE UPDATE ON instruments
    FOR EACH ROW EXECUTE FUNCTION keep_bound_market_assets();

CREATE FUNCTION keep_market_feed_binding() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'market feed binding and policy are immutable';
END;
$$;
CREATE TRIGGER market_feed_binding_immutable BEFORE UPDATE OR DELETE ON market_feeds
    FOR EACH ROW EXECUTE FUNCTION keep_market_feed_binding();

CREATE TABLE market_publisher_leases (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    market_feed_id bigint NOT NULL REFERENCES market_feeds(id),
    owner_id varchar(128) NOT NULL,
    epoch bigint NOT NULL CHECK (epoch >= 0),
    expires_at bigint NOT NULL CHECK (expires_at >= 0),
    CONSTRAINT uk_market_publisher_feed UNIQUE (market_feed_id),
    CONSTRAINT ck_market_publisher_owner CHECK (
        (epoch = 0 AND owner_id = '' AND expires_at = 0) OR
        (epoch > 0 AND length(owner_id) > 0)
    )
);

CREATE TABLE strategy_actions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    strategy_instance_id bigint NOT NULL,
    decision_key varchar(128) NOT NULL CHECK (length(decision_key) > 0),
    account_id varchar(64) NOT NULL,
    instrument_id bigint NOT NULL REFERENCES instruments(id),
    config_version bigint NOT NULL,
    kind varchar(16) NOT NULL CHECK (kind IN ('SUBMIT', 'CANCEL')),
    side varchar(8) NULL,
    price numeric(38,18) NULL,
    quantity numeric(38,18) NULL,
    time_in_force varchar(16) NULL,
    reduce_only boolean NOT NULL,
    idempotency_key varchar(128) NOT NULL CHECK (length(idempotency_key) > 0),
    client_order_id varchar(64) NOT NULL CHECK (length(client_order_id) > 0),
    state varchar(16) NOT NULL CHECK (state IN ('PENDING', 'DISPATCHING', 'WAITING', 'UNKNOWN', 'OBSERVED', 'DISCARDED')),
    deadline_at bigint NOT NULL CHECK (deadline_at >= 0),
    intent_id bigint NULL REFERENCES order_intents(id),
    cancellation_id bigint NULL REFERENCES cancellation_requests(id),
    observed_order_state varchar(32) NOT NULL CHECK (observed_order_state IN ('', 'INTENT', 'SUBMITTING', 'UNKNOWN', 'LIVE', 'PARTIALLY_FILLED', 'FILLED', 'CANCELED', 'REJECTED')),
    observed_cancellation_state varchar(16) NOT NULL CHECK (observed_cancellation_state IN ('', 'REQUESTED', 'SUBMITTING', 'PENDING', 'UNKNOWN', 'CONFIRMED', 'REJECTED')),
    owner_id varchar(128) NOT NULL CHECK (length(owner_id) > 0),
    owner_epoch bigint NOT NULL CHECK (owner_epoch > 0),
    revision bigint NOT NULL CHECK (revision > 0),
    CONSTRAINT uk_strategy_action_decision UNIQUE (strategy_instance_id, decision_key),
    CONSTRAINT uk_strategy_action_rpc_key UNIQUE (account_id, idempotency_key),
    CONSTRAINT fk_strategy_action_account FOREIGN KEY (strategy_instance_id, account_id) REFERENCES strategy_instances(id, account_id),
    CONSTRAINT fk_strategy_action_config FOREIGN KEY (strategy_instance_id, config_version) REFERENCES strategy_config_versions(instance_id, version),
    CONSTRAINT ck_strategy_action_payload CHECK (
        (kind = 'SUBMIT' AND side IS NOT NULL AND price IS NOT NULL AND quantity IS NOT NULL AND time_in_force IS NOT NULL
            AND side IN ('BUY', 'SELL') AND price > 0 AND price <> 'NaN'::numeric
            AND quantity > 0 AND quantity <> 'NaN'::numeric AND time_in_force IN ('GTC', 'POST_ONLY')
            AND (NOT reduce_only OR side = 'SELL') AND cancellation_id IS NULL)
        OR (kind = 'CANCEL' AND side IS NULL AND price IS NULL AND quantity IS NULL AND time_in_force IS NULL
            AND NOT reduce_only AND intent_id IS NOT NULL)
    ),
    CONSTRAINT ck_strategy_action_deadline CHECK (
        (state IN ('PENDING', 'DISCARDED') AND deadline_at = 0)
        OR (state IN ('DISPATCHING', 'WAITING', 'UNKNOWN', 'OBSERVED') AND deadline_at > 0)
    ),
    CONSTRAINT ck_strategy_action_observed CHECK (
        state <> 'OBSERVED' OR (intent_id IS NOT NULL AND
            ((kind = 'SUBMIT' AND observed_order_state IN ('LIVE', 'PARTIALLY_FILLED', 'FILLED', 'CANCELED', 'REJECTED'))
            OR (kind = 'CANCEL' AND cancellation_id IS NOT NULL AND observed_cancellation_state IN ('CONFIRMED', 'REJECTED'))))
    )
);

CREATE UNIQUE INDEX uk_strategy_action_active_submit ON strategy_actions(strategy_instance_id)
    WHERE kind = 'SUBMIT' AND state IN ('PENDING', 'DISPATCHING', 'WAITING', 'UNKNOWN');
CREATE UNIQUE INDEX uk_strategy_action_active_cancel ON strategy_actions(strategy_instance_id, intent_id)
    WHERE kind = 'CANCEL' AND state IN ('PENDING', 'DISPATCHING', 'WAITING', 'UNKNOWN');
CREATE INDEX idx_strategy_action_active ON strategy_actions(strategy_instance_id, id)
    WHERE state IN ('PENDING', 'DISPATCHING', 'WAITING', 'UNKNOWN');

CREATE FUNCTION protect_strategy_action_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'strategy action history is retained' USING ERRCODE = '23514', CONSTRAINT = 'strategy_action_identity';
    END IF;
    IF ROW(NEW.id, NEW.create_at, NEW.delete_at, NEW.strategy_instance_id, NEW.decision_key, NEW.account_id,
        NEW.instrument_id, NEW.config_version, NEW.kind, NEW.side, NEW.price, NEW.quantity, NEW.time_in_force,
        NEW.reduce_only, NEW.idempotency_key, NEW.client_order_id)
        IS DISTINCT FROM ROW(OLD.id, OLD.create_at, OLD.delete_at, OLD.strategy_instance_id, OLD.decision_key, OLD.account_id,
        OLD.instrument_id, OLD.config_version, OLD.kind, OLD.side, OLD.price, OLD.quantity, OLD.time_in_force,
        OLD.reduce_only, OLD.idempotency_key, OLD.client_order_id)
        OR NEW.revision <> OLD.revision + 1
        OR (OLD.intent_id IS NOT NULL AND NEW.intent_id IS DISTINCT FROM OLD.intent_id)
        OR (OLD.cancellation_id IS NOT NULL AND NEW.cancellation_id IS DISTINCT FROM OLD.cancellation_id)
        OR (OLD.deadline_at > 0 AND NEW.deadline_at <> OLD.deadline_at)
        OR NOT ((OLD.state = 'PENDING' AND NEW.state IN ('DISPATCHING', 'DISCARDED'))
            OR (OLD.state IN ('DISPATCHING', 'WAITING', 'UNKNOWN') AND NEW.state IN ('WAITING', 'UNKNOWN', 'OBSERVED'))) THEN
        RAISE EXCEPTION 'strategy action identity or transition rejected' USING ERRCODE = '23514', CONSTRAINT = 'strategy_action_identity';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER strategy_action_identity BEFORE UPDATE OR DELETE ON strategy_actions
    FOR EACH ROW EXECUTE FUNCTION protect_strategy_action_identity();

CREATE FUNCTION validate_strategy_action_authority() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    strategy strategy_instances%ROWTYPE;
    lease strategy_leases%ROWTYPE;
    parent order_intents%ROWTYPE;
    request cancellation_requests%ROWTYPE;
    now_ms bigint;
BEGIN
    -- The same strategy-first serialization as Go. NO KEY UPDATE remains
    -- compatible with FK KEY SHARE while excluding concurrent planners.
    SELECT * INTO strategy FROM strategy_instances WHERE id = NEW.strategy_instance_id FOR NO KEY UPDATE;
    SELECT * INTO lease FROM strategy_leases WHERE strategy_instance_id = NEW.strategy_instance_id FOR SHARE;
    now_ms := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
    IF strategy.id IS NULL OR strategy.delete_at IS NOT NULL OR strategy.account_id <> NEW.account_id
        OR strategy.instrument_id <> NEW.instrument_id OR lease.id IS NULL OR lease.delete_at IS NOT NULL
        OR lease.owner_id <> NEW.owner_id OR lease.epoch <> NEW.owner_epoch OR lease.expires_at <= now_ms THEN
        RAISE EXCEPTION 'strategy action authority rejected' USING ERRCODE = '23514', CONSTRAINT = 'strategy_action_fence';
    END IF;
    IF TG_OP = 'INSERT' THEN
        IF NEW.state <> 'PENDING' OR strategy.active_config_version IS DISTINCT FROM NEW.config_version THEN
            RAISE EXCEPTION 'strategy action must begin pending under active config' USING ERRCODE = '23514', CONSTRAINT = 'strategy_action_identity';
        END IF;
        IF (SELECT count(*) FROM strategy_actions WHERE strategy_instance_id = NEW.strategy_instance_id
            AND state IN ('PENDING', 'DISPATCHING', 'WAITING', 'UNKNOWN')) > 256 THEN
            RAISE EXCEPTION 'strategy action active capacity rejected' USING ERRCODE = '23514', CONSTRAINT = 'strategy_action_unresolved';
        END IF;
        IF NEW.kind = 'SUBMIT' AND (strategy.state <> 'RUNNING' OR NOT strategy.desired_running OR EXISTS (
            SELECT 1 FROM strategy_actions WHERE strategy_instance_id = NEW.strategy_instance_id AND id <> NEW.id
                AND state IN ('PENDING', 'DISPATCHING', 'WAITING', 'UNKNOWN'))) THEN
            RAISE EXCEPTION 'strategy action has unresolved work' USING ERRCODE = '23514', CONSTRAINT = 'strategy_action_unresolved';
        END IF;
    ELSIF OLD.state = 'PENDING' AND NEW.state = 'DISPATCHING' THEN
        IF strategy.active_config_version IS DISTINCT FROM NEW.config_version OR NEW.deadline_at <= now_ms
            OR NEW.deadline_at - now_ms > 60000 OR (NEW.kind = 'SUBMIT' AND (strategy.state <> 'RUNNING' OR NOT strategy.desired_running)) THEN
            RAISE EXCEPTION 'strategy action dispatch authority rejected' USING ERRCODE = '23514', CONSTRAINT = 'strategy_action_fence';
        END IF;
    END IF;
    IF NEW.intent_id IS NOT NULL THEN
        SELECT * INTO parent FROM order_intents WHERE id = NEW.intent_id FOR SHARE;
        IF parent.id IS NULL OR parent.delete_at IS NOT NULL OR parent.account_id <> NEW.account_id
            OR parent.strategy_instance_id <> NEW.strategy_instance_id OR parent.instrument_id <> NEW.instrument_id
            OR parent.client_order_id <> NEW.client_order_id
            OR (NEW.kind = 'SUBMIT' AND (parent.idempotency_key <> NEW.idempotency_key OR parent.config_version <> NEW.config_version
                OR parent.side IS DISTINCT FROM NEW.side OR parent.price IS DISTINCT FROM NEW.price OR parent.quantity IS DISTINCT FROM NEW.quantity
                OR parent.time_in_force IS DISTINCT FROM NEW.time_in_force OR parent.reduce_only <> NEW.reduce_only)) THEN
            RAISE EXCEPTION 'strategy action order identity rejected' USING ERRCODE = '23514', CONSTRAINT = 'strategy_action_identity';
        END IF;
    END IF;
    IF NEW.cancellation_id IS NOT NULL THEN
        SELECT * INTO request FROM cancellation_requests WHERE id = NEW.cancellation_id FOR SHARE;
        IF request.id IS NULL OR request.delete_at IS NOT NULL OR request.account_id <> NEW.account_id
            OR request.intent_id IS DISTINCT FROM NEW.intent_id OR request.idempotency_key <> NEW.idempotency_key THEN
            RAISE EXCEPTION 'strategy action cancellation identity rejected' USING ERRCODE = '23514', CONSTRAINT = 'strategy_action_identity';
        END IF;
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER strategy_action_fence AFTER INSERT OR UPDATE ON strategy_actions
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_strategy_action_authority();

CREATE TABLE admin_users (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    username varchar(64) NOT NULL CONSTRAINT uk_admin_user_name UNIQUE,
    password_hash varchar(60) NOT NULL,
    role varchar(16) NOT NULL CHECK (role IN ('viewer', 'operator', 'admin')),
    enabled boolean NOT NULL,
    credential_version bigint NOT NULL CHECK (credential_version > 0),
    failed_attempts integer NOT NULL CHECK (failed_attempts BETWEEN 0 AND 5),
    locked_until bigint NOT NULL CHECK (locked_until >= 0),
    revision bigint NOT NULL CHECK (revision > 0),
    CONSTRAINT ck_admin_user_name CHECK (username ~ '^[a-z0-9][a-z0-9_.-]{2,63}$'),
    CONSTRAINT ck_admin_user_password CHECK (password_hash ~ '^\$2a\$12\$[./A-Za-z0-9]{53}$')
);
CREATE FUNCTION guard_admin_credentials() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.username IS DISTINCT FROM OLD.username OR NEW.credential_version < OLD.credential_version OR
       (ROW(NEW.password_hash, NEW.role, NEW.enabled, NEW.delete_at) IS DISTINCT FROM
        ROW(OLD.password_hash, OLD.role, OLD.enabled, OLD.delete_at) AND NEW.credential_version <> OLD.credential_version + 1) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_credentials', MESSAGE = 'credential changes require a new version';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER admin_credentials BEFORE UPDATE ON admin_users FOR EACH ROW EXECUTE FUNCTION guard_admin_credentials();

CREATE TABLE admin_sessions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    user_id bigint NOT NULL REFERENCES admin_users(id),
    token_hash char(64) NOT NULL CONSTRAINT uk_admin_session_token UNIQUE CHECK (token_hash ~ '^[0-9a-f]{64}$'),
    csrf_hash char(64) NOT NULL CHECK (csrf_hash ~ '^[0-9a-f]{64}$'),
    credential_version bigint NOT NULL CHECK (credential_version > 0),
    expires_at bigint NOT NULL CHECK (expires_at > create_at),
    revoked_at bigint NULL CHECK (revoked_at IS NULL OR revoked_at > 0)
);
CREATE INDEX idx_admin_session_user ON admin_sessions(user_id, id);
CREATE FUNCTION guard_admin_session() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_session_history', MESSAGE = 'session history must be retained';
    END IF;
    IF ROW(NEW.user_id, NEW.token_hash, NEW.csrf_hash, NEW.credential_version, NEW.expires_at, NEW.create_at, NEW.delete_at) IS DISTINCT FROM
       ROW(OLD.user_id, OLD.token_hash, OLD.csrf_hash, OLD.credential_version, OLD.expires_at, OLD.create_at, OLD.delete_at) OR
       (OLD.revoked_at IS NOT NULL AND NEW.revoked_at IS DISTINCT FROM OLD.revoked_at) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_session_history', MESSAGE = 'session identity, expiry and revocation are immutable';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER admin_session_history BEFORE UPDATE OR DELETE ON admin_sessions FOR EACH ROW EXECUTE FUNCTION guard_admin_session();

CREATE TABLE admin_audits (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    actor varchar(64) NOT NULL CHECK (length(actor) > 0),
    actor_role varchar(16) NOT NULL CHECK (actor_role IN ('viewer', 'operator', 'admin')),
    action varchar(64) NOT NULL CHECK (action ~ '^[a-z][a-z0-9_.-]{1,63}$'),
    resource varchar(128) NOT NULL CHECK (length(resource) > 0),
    reason varchar(256) NOT NULL CHECK (length(reason) > 0),
    before_version bigint NULL CHECK (before_version IS NULL OR before_version > 0),
    after_version bigint NULL CHECK (after_version IS NULL OR after_version > 0)
);
CREATE FUNCTION keep_admin_audit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_audit_history', MESSAGE = 'management audit history is immutable';
END;
$$;
CREATE TRIGGER admin_audit_history BEFORE UPDATE OR DELETE ON admin_audits FOR EACH ROW EXECUTE FUNCTION keep_admin_audit();

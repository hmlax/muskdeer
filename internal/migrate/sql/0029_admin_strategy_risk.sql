CREATE TABLE admin_strategy_risk_changes (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL CHECK (delete_at IS NULL),
    actor_user_id bigint NOT NULL REFERENCES admin_users(id),
    actor_session_id bigint NOT NULL REFERENCES admin_sessions(id),
    strategy_instance_id bigint NOT NULL REFERENCES strategy_instances(id),
    audit_id bigint NOT NULL CONSTRAINT uk_admin_strategy_risk_audit UNIQUE REFERENCES admin_audits(id),
    idempotency_key varchar(64) NOT NULL CHECK (idempotency_key ~ '^[A-Za-z0-9_.:-]{16,64}$'),
    request_fingerprint char(64) NOT NULL CHECK (request_fingerprint ~ '^[0-9a-f]{64}$'),
    action varchar(32) NOT NULL CHECK (action IN ('risk.strategy.block', 'risk.strategy.unblock')),
    previous_enabled boolean NOT NULL,
    enabled boolean NOT NULL CHECK (enabled = (action = 'risk.strategy.unblock')),
    previous_revision bigint NOT NULL CHECK (previous_revision > 0),
    revision bigint NOT NULL CHECK (revision > previous_revision AND revision - previous_revision = 1),
    reason varchar(256) NOT NULL CHECK (length(reason) > 0 AND octet_length(reason) <= 256),
    recovery_until bigint NULL,
    expected_config_version bigint NULL,
    expected_desired_state varchar(16) NULL,
    CONSTRAINT ck_admin_strategy_risk_recovery CHECK (
        (NOT enabled AND recovery_until IS NULL AND expected_config_version IS NULL AND expected_desired_state IS NULL)
        OR (enabled AND recovery_until IS NOT NULL AND recovery_until > 0 AND expected_config_version IS NOT NULL AND expected_config_version > 0
            AND expected_desired_state IS NOT NULL AND expected_desired_state IN ('RUNNING', 'PAUSED', 'STOPPED'))
    ),
    CONSTRAINT uk_admin_strategy_risk_key UNIQUE (actor_user_id, idempotency_key),
    CONSTRAINT uk_admin_strategy_risk_revision UNIQUE (strategy_instance_id, revision)
);

CREATE FUNCTION keep_admin_strategy_risk_history() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_risk_history', MESSAGE = 'risk control history is immutable';
END;
$$;
CREATE TRIGGER admin_strategy_risk_history BEFORE UPDATE OR DELETE ON admin_strategy_risk_changes
    FOR EACH ROW EXECUTE FUNCTION keep_admin_strategy_risk_history();

-- Receipt revisions are independent of the frequently changing monetary
-- budget revision. One strategy mutex serializes new control effects. Verify
-- authority again at COMMIT: a session or recovery observation may expire
-- while an audit/receipt write or commit fence is waiting.
CREATE FUNCTION guard_admin_strategy_risk_change() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    principal admin_users%ROWTYPE;
    session admin_sessions%ROWTYPE;
    strategy strategy_instances%ROWTYPE;
    budget strategy_budgets%ROWTYPE;
    audit admin_audits%ROWTYPE;
    previous_revision bigint;
    now_ms bigint;
BEGIN
    SELECT * INTO principal FROM admin_users WHERE id = NEW.actor_user_id FOR SHARE;
    SELECT * INTO session FROM admin_sessions WHERE id = NEW.actor_session_id FOR SHARE;
    SELECT * INTO strategy FROM strategy_instances WHERE id = NEW.strategy_instance_id FOR SHARE;
    SELECT * INTO budget FROM strategy_budgets WHERE strategy_instance_id = NEW.strategy_instance_id FOR SHARE;
    now_ms := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
    IF principal.id IS NULL OR session.id IS NULL OR NOT principal.enabled OR principal.delete_at IS NOT NULL OR
       principal.role NOT IN ('operator', 'admin') OR (NEW.enabled AND principal.role <> 'admin') OR
       session.user_id <> principal.id OR session.delete_at IS NOT NULL OR session.revoked_at IS NOT NULL OR
       session.credential_version <> principal.credential_version OR session.expires_at <= now_ms THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_risk_authority', MESSAGE = 'risk control requires current authority';
    END IF;
    SELECT COALESCE(max(revision), 1) INTO previous_revision FROM admin_strategy_risk_changes
        WHERE strategy_instance_id = NEW.strategy_instance_id AND id <> NEW.id;
    SELECT * INTO audit FROM admin_audits WHERE id = NEW.audit_id;
    IF audit.id IS NULL OR audit.delete_at IS NOT NULL OR audit.actor <> principal.username OR audit.actor_role <> principal.role OR
       audit.action <> NEW.action OR audit.resource <> 'strategy_risk:' || NEW.strategy_instance_id::text OR
       audit.reason <> NEW.reason OR audit.before_version IS DISTINCT FROM NEW.previous_revision OR audit.after_version IS DISTINCT FROM NEW.revision THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_risk_audit', MESSAGE = 'risk control requires matching audit';
    END IF;
    IF strategy.id IS NULL OR strategy.delete_at IS NOT NULL OR budget.id IS NULL OR budget.delete_at IS NOT NULL OR
       budget.account_id <> strategy.account_id OR budget.enabled <> NEW.enabled OR previous_revision <> NEW.previous_revision OR
       EXISTS (SELECT 1 FROM risk_snapshots WHERE strategy_instance_id = strategy.id AND delete_at IS NULL AND allow_new_risk) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_risk_effect', MESSAGE = 'risk control requires its scoped flag and closed cached risk';
    END IF;
    IF NEW.enabled AND (NEW.recovery_until <= now_ms OR NEW.recovery_until > now_ms + 5000 OR
       strategy.requested_config_version <> NEW.expected_config_version OR strategy.desired_state <> NEW.expected_desired_state OR
       budget.reserved_notional <> 0 OR
       EXISTS (SELECT 1 FROM order_intents WHERE strategy_instance_id = strategy.id AND delete_at IS NULL
           AND state IN ('INTENT', 'SUBMITTING', 'LIVE', 'PARTIALLY_FILLED', 'UNKNOWN')) OR
       EXISTS (SELECT 1 FROM simulator_orders WHERE strategy_instance_id = strategy.id AND delete_at IS NULL
           AND state IN ('LIVE', 'PARTIALLY_FILLED')) OR
       EXISTS (SELECT 1 FROM strategy_actions WHERE strategy_instance_id = strategy.id AND delete_at IS NULL
           AND state IN ('PENDING', 'DISPATCHING', 'WAITING', 'UNKNOWN')) OR
       EXISTS (SELECT 1 FROM cancellation_requests WHERE strategy_instance_id = strategy.id AND delete_at IS NULL
           AND state IN ('REQUESTED', 'SUBMITTING', 'PENDING', 'UNKNOWN'))) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', CONSTRAINT = 'admin_risk_recovery', MESSAGE = 'risk recovery observation is no longer valid';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER admin_strategy_risk_commit AFTER INSERT ON admin_strategy_risk_changes
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION guard_admin_strategy_risk_change();

-- OMS already enforces enabled budgets. Apply the same managed-strategy flag
-- even to a direct simulator command with no intent_id. Historical unmanaged
-- core-only scenarios have no strategy budget; this does not provision one.
-- Cancellation still uses its existing owner/fencing checks and may release
-- confirmed obligations while new risk is blocked.
CREATE FUNCTION validate_simulator_admin_risk() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    budget strategy_budgets%ROWTYPE;
BEGIN
    IF NEW.action = 'CANCEL' THEN
        RETURN NULL;
    END IF;
    PERFORM 1 FROM strategy_instances WHERE id = NEW.strategy_instance_id FOR NO KEY UPDATE;
    SELECT * INTO budget FROM strategy_budgets WHERE strategy_instance_id = NEW.strategy_instance_id FOR SHARE;
    IF budget.id IS NOT NULL AND (budget.delete_at IS NOT NULL OR NOT budget.enabled OR budget.account_id <> NEW.account_id) THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001', CONSTRAINT = 'simulator_admin_risk', MESSAGE = 'managed strategy new risk is disabled';
    END IF;
    RETURN NULL;
END;
$$;
CREATE CONSTRAINT TRIGGER simulator_admin_risk AFTER INSERT ON simulator_commands
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_simulator_admin_risk();

CREATE TABLE risk_budgets (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL,
    scope_kind varchar(16) NOT NULL CHECK (scope_kind IN ('PLATFORM', 'INSTRUMENT')),
    scope_key varchar(64) NOT NULL,
    instrument_id bigint NULL REFERENCES instruments(id),
    asset varchar(32) NOT NULL CHECK (length(asset) > 0),
    limit_notional numeric(76,36) NOT NULL CHECK (limit_notional > 0 AND limit_notional <> 'NaN'::numeric),
    reserved_notional numeric(76,36) NOT NULL CHECK (reserved_notional >= 0 AND reserved_notional <= limit_notional AND reserved_notional <> 'NaN'::numeric),
    maximum_order_notional numeric(76,36) NOT NULL CHECK (maximum_order_notional > 0 AND maximum_order_notional <= limit_notional AND maximum_order_notional <> 'NaN'::numeric),
    enabled boolean NOT NULL,
    revision bigint NOT NULL CHECK (revision > 0),
    CONSTRAINT uk_risk_budget_scope UNIQUE (scope_kind, scope_key),
    CONSTRAINT ck_risk_budget_scope CHECK (
        (scope_kind = 'PLATFORM' AND instrument_id IS NULL AND scope_key = asset)
        OR (scope_kind = 'INSTRUMENT' AND instrument_id IS NOT NULL AND scope_key = instrument_id::text)
    )
);
CREATE INDEX idx_order_intent_instrument ON order_intents(instrument_id);


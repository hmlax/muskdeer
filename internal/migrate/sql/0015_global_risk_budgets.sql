CREATE FUNCTION keep_risk_budget_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'risk budget history must be retained';
    END IF;
    IF TG_OP = 'UPDATE' AND ROW(NEW.id, NEW.create_at, NEW.scope_kind, NEW.scope_key, NEW.instrument_id, NEW.asset)
        IS DISTINCT FROM ROW(OLD.id, OLD.create_at, OLD.scope_kind, OLD.scope_key, OLD.instrument_id, OLD.asset) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'risk budget scope is immutable';
    END IF;
    IF NEW.scope_kind = 'INSTRUMENT' AND NEW.asset IS DISTINCT FROM (SELECT quote_asset FROM instruments WHERE id = NEW.instrument_id) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'risk budget quote asset differs from instrument';
    END IF;
    IF NEW.delete_at IS NOT NULL AND (NEW.enabled OR NEW.reserved_notional <> 0) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'active risk budget cannot be retired';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER risk_budget_identity BEFORE INSERT OR UPDATE OR DELETE ON risk_budgets
    FOR EACH ROW EXECUTE FUNCTION keep_risk_budget_identity();

CREATE FUNCTION check_risk_budget_total(budget_id bigint) RETURNS void LANGUAGE plpgsql AS $$
DECLARE
    budget risk_budgets%ROWTYPE;
    total numeric;
BEGIN
    SELECT * INTO budget FROM risk_budgets WHERE id = budget_id FOR UPDATE;
    SELECT COALESCE(sum(o.reserved_quote_notional), 0) INTO total
    FROM order_intents o JOIN instruments i ON i.id = o.instrument_id
    WHERE o.delete_at IS NULL AND i.quote_asset = budget.asset
        AND (budget.scope_kind = 'PLATFORM' OR o.instrument_id = budget.instrument_id);
    IF budget.id IS NULL OR budget.reserved_notional IS DISTINCT FROM total THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'global risk reservation differs from durable obligations', CONSTRAINT = 'risk_budget_total';
    END IF;
END;
$$;
CREATE FUNCTION validate_risk_budget_total() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    PERFORM check_risk_budget_total(NEW.id);
    RETURN NEW;
END;
$$;
CREATE CONSTRAINT TRIGGER risk_budget_total AFTER INSERT OR UPDATE ON risk_budgets
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_risk_budget_total();

CREATE FUNCTION keep_intent_risk_identity() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'intent history must be retained';
    END IF;
    IF ROW(NEW.id, NEW.create_at, NEW.account_id, NEW.strategy_instance_id, NEW.instrument_id, NEW.config_version,
        NEW.client_order_id, NEW.idempotency_key, NEW.price, NEW.quantity, NEW.time_in_force, NEW.reduce_only, NEW.fingerprint)
        IS DISTINCT FROM ROW(OLD.id, OLD.create_at, OLD.account_id, OLD.strategy_instance_id, OLD.instrument_id, OLD.config_version,
        OLD.client_order_id, OLD.idempotency_key, OLD.price, OLD.quantity, OLD.time_in_force, OLD.reduce_only, OLD.fingerprint)
        OR (NEW.delete_at IS NOT NULL AND NEW.reserved_quote_notional <> 0) THEN
        RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'intent business identity or outstanding obligation changed';
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER intent_risk_identity BEFORE UPDATE OR DELETE ON order_intents
    FOR EACH ROW EXECUTE FUNCTION keep_intent_risk_identity();

CREATE FUNCTION validate_intent_global_reservation() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    budget risk_budgets%ROWTYPE;
    selected_asset varchar(32);
    count integer := 0;
BEGIN
    SELECT quote_asset INTO selected_asset FROM instruments WHERE id = NEW.instrument_id;
    FOR budget IN SELECT * FROM risk_budgets WHERE delete_at IS NULL AND asset = selected_asset
        AND ((scope_kind = 'PLATFORM' AND scope_key = selected_asset)
            OR (scope_kind = 'INSTRUMENT' AND instrument_id = NEW.instrument_id)) ORDER BY id FOR UPDATE LOOP
        count := count + 1;
        PERFORM check_risk_budget_total(budget.id);
    END LOOP;
    IF count <> 2 AND NEW.reserved_quote_notional > 0 THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'global risk budget is missing', CONSTRAINT = 'oms_global_risk';
    END IF;
    RETURN NEW;
END;
$$;
CREATE CONSTRAINT TRIGGER intent_global_reservation AFTER INSERT OR UPDATE ON order_intents
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_intent_global_reservation();

CREATE FUNCTION validate_simulator_global_risk() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    intent order_intents%ROWTYPE;
    budget risk_budgets%ROWTYPE;
    selected_asset varchar(32);
    count integer := 0;
BEGIN
    IF NEW.intent_id IS NULL OR NEW.action = 'CANCEL' THEN
        RETURN NEW;
    END IF;
    SELECT * INTO intent FROM order_intents WHERE id = NEW.intent_id FOR SHARE;
    SELECT quote_asset INTO selected_asset FROM instruments WHERE id = NEW.instrument_id;
    FOR budget IN SELECT * FROM risk_budgets WHERE delete_at IS NULL AND asset = selected_asset
        AND ((scope_kind = 'PLATFORM' AND scope_key = selected_asset)
            OR (scope_kind = 'INSTRUMENT' AND instrument_id = NEW.instrument_id)) ORDER BY id FOR SHARE LOOP
        count := count + 1;
        IF NOT budget.enabled OR intent.price * intent.quantity > budget.maximum_order_notional
            OR budget.reserved_notional < intent.reserved_quote_notional THEN
            RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'global risk budget rejected', CONSTRAINT = 'oms_global_risk';
        END IF;
    END LOOP;
    IF count <> 2 THEN
        RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = 'global risk budget is missing', CONSTRAINT = 'oms_global_risk';
    END IF;
    RETURN NEW;
END;
$$;
CREATE CONSTRAINT TRIGGER simulator_global_risk AFTER INSERT ON simulator_commands
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_simulator_global_risk();

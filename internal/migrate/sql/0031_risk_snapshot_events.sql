CREATE TABLE risk_snapshot_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_at bigint NOT NULL,
    update_at bigint NOT NULL,
    delete_at bigint NULL CHECK (delete_at IS NULL),
    -- Historical references survive source removal; they are not live grants.
    risk_snapshot_id bigint NOT NULL CHECK (risk_snapshot_id > 0),
    risk_snapshot_revision bigint NOT NULL CHECK (risk_snapshot_revision > 0),
    kind varchar(16) NOT NULL CHECK (kind IN ('BASELINE', 'CHANGED', 'REMOVED')),
    strategy_instance_id bigint NOT NULL,
    account_id varchar(64) NOT NULL,
    instrument_id bigint NOT NULL REFERENCES instruments(id),
    config_version bigint NOT NULL,
    market_data_source varchar(32) NOT NULL CHECK (market_data_source IN ('binance', 'okx')),
    market_feed_id bigint NULL,
    market_epoch bigint NOT NULL CHECK (market_epoch >= 0),
    market_sequence bigint NOT NULL CHECK (market_sequence >= 0),
    market_revision bigint NOT NULL CHECK (market_revision >= 0),
    market_source_version bigint NOT NULL CHECK (market_source_version >= 0),
    market_maximum_age_ms bigint NOT NULL CHECK (market_maximum_age_ms > 0 AND market_maximum_age_ms <= 5000),
    observed_at bigint NOT NULL CHECK (observed_at > 0),
    expires_at bigint NOT NULL CHECK (expires_at > observed_at AND expires_at - observed_at <= 5000),
    reconciled boolean NOT NULL,
    allow_new_risk boolean NOT NULL,
    reason_code varchar(32) NOT NULL,
    snapshot_deleted boolean NOT NULL,
    CONSTRAINT fk_risk_event_account FOREIGN KEY (strategy_instance_id, account_id) REFERENCES strategy_instances(id, account_id),
    CONSTRAINT fk_risk_event_config FOREIGN KEY (strategy_instance_id, config_version) REFERENCES strategy_config_versions(instance_id, version)
);
CREATE INDEX idx_risk_event_strategy ON risk_snapshot_events(strategy_instance_id, id);
CREATE INDEX idx_risk_event_account ON risk_snapshot_events(account_id, id);
CREATE INDEX idx_risk_event_snapshot ON risk_snapshot_events(risk_snapshot_id, id);

-- Bound by the migration caller's context. Serialize the recording start with
-- source writers so there is no gap between baseline and live capture.
LOCK TABLE risk_snapshots IN SHARE ROW EXCLUSIVE MODE;

CREATE FUNCTION record_risk_snapshot_event() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    source_row risk_snapshots%ROWTYPE;
    recording_kind varchar(16);
    recorded_ms bigint;
BEGIN
    IF TG_OP = 'UPDATE' THEN
        -- Routine sequence/revision/observation/expiry refreshes do not create
        -- a new diagnostic transition. Authority/configuration and policy do.
        IF ROW(NEW.strategy_instance_id, NEW.account_id, NEW.instrument_id, NEW.config_version,
            NEW.market_data_source, NEW.market_feed_id, NEW.market_epoch, NEW.market_source_version,
            NEW.market_maximum_age_ms, NEW.reconciled, NEW.allow_new_risk, NEW.reason_code, NEW.delete_at IS NOT NULL)
            IS NOT DISTINCT FROM ROW(OLD.strategy_instance_id, OLD.account_id, OLD.instrument_id, OLD.config_version,
            OLD.market_data_source, OLD.market_feed_id, OLD.market_epoch, OLD.market_source_version,
            OLD.market_maximum_age_ms, OLD.reconciled, OLD.allow_new_risk, OLD.reason_code, OLD.delete_at IS NOT NULL) THEN
            RETURN NEW;
        END IF;
        source_row := NEW;
        recording_kind := 'CHANGED';
    ELSIF TG_OP = 'INSERT' THEN
        source_row := NEW;
        recording_kind := 'BASELINE';
    ELSE
        source_row := OLD;
        recording_kind := 'REMOVED';
    END IF;
    recorded_ms := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
    INSERT INTO risk_snapshot_events (
        create_at, update_at, delete_at, risk_snapshot_id, risk_snapshot_revision, kind,
        strategy_instance_id, account_id, instrument_id, config_version, market_data_source,
        market_feed_id, market_epoch, market_sequence, market_revision, market_source_version,
        market_maximum_age_ms, observed_at, expires_at, reconciled, allow_new_risk, reason_code, snapshot_deleted
    ) VALUES (
        recorded_ms, recorded_ms, NULL, source_row.id, source_row.revision, recording_kind,
        source_row.strategy_instance_id, source_row.account_id, source_row.instrument_id,
        source_row.config_version, source_row.market_data_source, source_row.market_feed_id,
        source_row.market_epoch, source_row.market_sequence, source_row.market_revision,
        source_row.market_source_version, source_row.market_maximum_age_ms, source_row.observed_at,
        source_row.expires_at, source_row.reconciled, source_row.allow_new_risk, source_row.reason_code,
        source_row.delete_at IS NOT NULL OR TG_OP = 'DELETE'
    );
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;
CREATE TRIGGER risk_snapshot_diagnostic_history AFTER INSERT OR UPDATE OR DELETE ON risk_snapshots
    FOR EACH ROW EXECUTE FUNCTION record_risk_snapshot_event();

-- Existing rows only establish the first available recording. This migration
-- does not pretend to reconstruct earlier risk transitions or alter source data.
DO $$
DECLARE
    recorded_ms bigint := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
BEGIN
    INSERT INTO risk_snapshot_events (
        create_at, update_at, delete_at, risk_snapshot_id, risk_snapshot_revision, kind,
        strategy_instance_id, account_id, instrument_id, config_version, market_data_source,
        market_feed_id, market_epoch, market_sequence, market_revision, market_source_version,
        market_maximum_age_ms, observed_at, expires_at, reconciled, allow_new_risk, reason_code, snapshot_deleted
    ) SELECT recorded_ms, recorded_ms, NULL, s.id, s.revision, 'BASELINE',
        s.strategy_instance_id, s.account_id, s.instrument_id, s.config_version, s.market_data_source,
        s.market_feed_id, s.market_epoch, s.market_sequence, s.market_revision, s.market_source_version,
        s.market_maximum_age_ms, s.observed_at, s.expires_at, s.reconciled, s.allow_new_risk, s.reason_code,
        s.delete_at IS NOT NULL
        FROM risk_snapshots AS s ORDER BY s.id;
END;
$$;

CREATE FUNCTION keep_risk_snapshot_event_immutable() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION USING ERRCODE = '23514', MESSAGE = 'risk snapshot diagnostic history is immutable';
END;
$$;
CREATE TRIGGER risk_snapshot_event_immutable BEFORE UPDATE OR DELETE ON risk_snapshot_events
    FOR EACH ROW EXECUTE FUNCTION keep_risk_snapshot_event_immutable();

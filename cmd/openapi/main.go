// Command openapi generates or checks the management HTTP contract.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"io"
	"os"

	"github.com/hmlax/muskdeer/internal/adminopenapi"
)

func main() {
	if err := run(os.Args[1:], os.Stdout); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(arguments []string, output io.Writer) error {
	flags := flag.NewFlagSet("openapi", flag.ContinueOnError)
	check := flags.Bool("check", false, "compare generated bytes without writing")
	path := flags.String("output", "docs/openapi.json", "repository document path")
	if err := flags.Parse(arguments); err != nil {
		return err
	}
	if flags.NArg() != 0 {
		return fmt.Errorf("openapi accepts no positional arguments")
	}
	data, err := adminopenapi.Generate()
	if err != nil {
		return err
	}
	if *check {
		existing, err := os.ReadFile(*path)
		if err != nil {
			return fmt.Errorf("read OpenAPI: %w", err)
		}
		if !bytes.Equal(existing, data) {
			return fmt.Errorf("OpenAPI differs: run make openapi-generate")
		}
	} else if err := os.WriteFile(*path, data, 0644); err != nil {
		return fmt.Errorf("write OpenAPI: %w", err)
	}
	_, err = fmt.Fprintln(output, "Management OpenAPI 3.1 contract checked/generated")
	return err
}
